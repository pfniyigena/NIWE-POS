-- Property Management phase PM-17: utilities and service charges added to the tenant's rent invoice.
-- A charge type is a name (Service charge, Water, Electricity...) with its own service product. A lease can carry fixed monthly charges and
-- metered ones (a meter and a rate per unit); readings and one-off charges wait as PENDING until the next rent invoice of the lease takes them.
-- What an invoice took is kept line by line (pm_billed_charge) so the screens and the report can show it. The money is the agency's: the owner
-- statement counts only the rent part of what the tenant pays (rent first).

create table pm_charge_type (
    id bigint generated by default as identity not null,
    name character varying(100) not null,
    kind character varying(8) not null,
    unit_label character varying(20),
    default_amount numeric(18,2),
    active boolean not null,
    product_id bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_charge_type_pkey primary key (id),
    constraint pm_charge_type_name_key unique (name),
    constraint pm_charge_type_kind_check check (kind in ('FIXED', 'METERED'))
);

create table pm_lease_charge (
    id bigint generated by default as identity not null,
    lease_id bigint not null,
    charge_type_id bigint not null,
    amount numeric(18,4) not null,
    start_date date not null,
    end_date date,
    opening_reading numeric(18,3),
    note character varying(300),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_lease_charge_pkey primary key (id)
);

create index idx_pm_lease_charge_lease on pm_lease_charge using btree (lease_id);

create table pm_extra_charge (
    id bigint generated by default as identity not null,
    lease_id bigint not null,
    lease_charge_id bigint,
    charge_type_id bigint,
    kind character varying(8) not null,
    charge_date date not null,
    description character varying(300) not null,
    quantity numeric(18,3),
    unit_label character varying(20),
    rate numeric(18,4),
    amount numeric(18,2) not null,
    reading_from numeric(18,3),
    reading_to numeric(18,3),
    status character varying(10) not null,
    rent_charge_id bigint,
    invoice_number character varying(60),
    note character varying(300),
    created_by_name character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_extra_charge_pkey primary key (id),
    constraint pm_extra_charge_kind_check check (kind in ('METER', 'ONE_OFF')),
    constraint pm_extra_charge_status_check check (status in ('PENDING', 'BILLED', 'CANCELLED'))
);

create index idx_pm_extra_charge_lease on pm_extra_charge using btree (lease_id);

create index idx_pm_extra_charge_rent on pm_extra_charge using btree (rent_charge_id);

create table pm_billed_charge (
    id bigint generated by default as identity not null,
    rent_charge_id bigint not null,
    lease_id bigint not null,
    charge_type_id bigint,
    name character varying(100) not null,
    description character varying(400) not null,
    source character varying(8) not null,
    extra_id bigint,
    amount numeric(18,2) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_billed_charge_pkey primary key (id),
    constraint pm_billed_charge_source_check check (source in ('FIXED', 'METER', 'ONE_OFF'))
);

create index idx_pm_billed_charge_rent on pm_billed_charge using btree (rent_charge_id);

create index idx_pm_billed_charge_lease on pm_billed_charge using btree (lease_id);

alter table pm_rent_charge add column extras numeric(18,2) not null default 0;

alter table pm_settings add column charges_product_id bigint;
