-- v1.39.0: reminders for abandoned carts. When the shop switches it on and a customer types an e-mail address at checkout, the cart is kept
-- (one cart per address) and the customer gets at most two reminders: 1 hour and 3 days after the last change. No discount; the e-mail only
-- lists the cart as it is on the shop today and links back to it. Every e-mail has a link that stops the reminders.

alter table online_store_settings add column cart_reminders_enabled boolean not null default false;

create table online_cart (
    id bigint generated by default as identity,
    email varchar(160) not null,
    language varchar(2) not null default 'en',
    token varchar(48) not null,
    status varchar(10) not null default 'ACTIVE',
    saved_at timestamp(6) with time zone not null,
    reminder_count integer not null default 0,
    first_reminder_at timestamp(6) with time zone,
    second_reminder_at timestamp(6) with time zone,
    recovered_at timestamp(6) with time zone,
    attempts integer not null default 0,
    next_try_at timestamp(6) with time zone,
    last_error varchar(200),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_cart_pkey primary key (id),
    constraint online_cart_email_uk unique (email),
    constraint online_cart_token_uk unique (token),
    constraint online_cart_status_ck check (status in ('ACTIVE', 'REMINDED', 'DONE', 'RECOVERED', 'STOPPED', 'EXPIRED'))
);
create index online_cart_status_saved_idx on online_cart (status, saved_at);

create table online_cart_line (
    id bigint generated by default as identity,
    cart_id bigint not null,
    product_id bigint not null,
    quantity integer not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_cart_line_pkey primary key (id),
    constraint online_cart_line_cart_fk foreign key (cart_id) references online_cart (id) on delete cascade
);
create index online_cart_line_cart_idx on online_cart_line (cart_id);
