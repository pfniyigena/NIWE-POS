-- RS-7: cash events (deposits and manual paid-in / paid-out) and the daily close (Z-report).
create table restaurant_cash_event (
    id bigint generated by default as identity not null,
    kind character varying(24) not null,
    method character varying(40),
    amount numeric(38,2) not null,
    reservation_id bigint,
    label character varying(160),
    reason character varying(200),
    by_user character varying(80),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint restaurant_cash_event_pkey primary key (id)
);
create index restaurant_cash_event_created_idx on restaurant_cash_event (created_at);

create table restaurant_day_close (
    id bigint generated by default as identity not null,
    business_date date not null,
    z_number integer not null,
    status character varying(10) not null default 'CLOSED',
    opening_float numeric(38,2) not null default 0,
    cash_expected numeric(38,2) not null default 0,
    cash_counted numeric(38,2) not null default 0,
    variance numeric(38,2) not null default 0,
    float_kept numeric(38,2) not null default 0,
    banked numeric(38,2) not null default 0,
    checks integer not null default 0,
    net_sales numeric(38,2) not null default 0,
    total_billed numeric(38,2) not null default 0,
    tips numeric(38,2) not null default 0,
    notes character varying(300),
    closed_by character varying(80),
    closed_at timestamp(6) with time zone,
    reopened_by character varying(80),
    reopened_at timestamp(6) with time zone,
    reopen_reason character varying(200),
    snapshot text,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint restaurant_day_close_pkey primary key (id)
);
create unique index restaurant_day_close_active_uq on restaurant_day_close (business_date) where status = 'CLOSED';
