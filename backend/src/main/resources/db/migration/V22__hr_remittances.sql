-- HR-4: payments of the withheld income tax (PAYE), social security and other payroll payables to the authorities.
create table payroll_remittance (
    id bigint generated by default as identity not null,
    kind character varying(20) not null,
    period_year integer not null,
    period_month integer not null,
    amount numeric(19,2) not null,
    paid_on date not null,
    reference character varying(120),
    paid_to character varying(160),
    note character varying(300),
    status character varying(10) not null default 'ACTIVE',
    void_note character varying(300),
    voided_by_name character varying(120),
    created_by_name character varying(120),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint payroll_remittance_pkey primary key (id),
    constraint payroll_remittance_kind_check check (kind in ('PAYE', 'SOCIAL_SECURITY', 'OTHER')),
    constraint payroll_remittance_status_check check (status in ('ACTIVE', 'VOIDED'))
);
create index payroll_remittance_period_idx on payroll_remittance (period_year, period_month);
