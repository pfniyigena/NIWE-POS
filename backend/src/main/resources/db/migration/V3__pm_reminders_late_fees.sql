-- Property Management: rent reminders to tenants and late fees on overdue rent. See "Rent reminders and late fees" in README.md.

alter table pm_settings add column reminders_enabled boolean default false not null;
alter table pm_settings add column reminder_before_days integer default 3 not null;
alter table pm_settings add column overdue_first_days integer default 3 not null;
alter table pm_settings add column overdue_repeat_days integer default 7 not null;
alter table pm_settings add column overdue_max_reminders integer default 3 not null;
alter table pm_settings add column late_fee_enabled boolean default false not null;
alter table pm_settings add column late_fee_auto boolean default false not null;
alter table pm_settings add column late_fee_grace_days integer default 5 not null;
alter table pm_settings add column late_fee_type character varying(10) default 'PERCENT' not null;
alter table pm_settings add column late_fee_value numeric(18,2);
alter table pm_settings add column late_fee_max numeric(18,2);
alter table pm_settings add column late_fee_product_id bigint;
alter table pm_settings add column reminders_last_run date;
alter table pm_settings add column reminders_last_summary character varying(500);

create table pm_rent_reminder (
    id bigint generated by default as identity not null,
    rent_charge_id bigint not null,
    sent_at timestamp(6) with time zone not null,
    kind character varying(10) not null,
    sent_to character varying(255) not null,
    sent_by character varying(120),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_rent_reminder_pkey primary key (id),
    constraint pm_rent_reminder_kind_check check (kind in ('BEFORE', 'OVERDUE', 'MANUAL'))
);

create index idx_pm_rent_reminder_rent_charge_id on pm_rent_reminder using btree (rent_charge_id);

create table pm_late_fee (
    id bigint generated by default as identity not null,
    rent_charge_id bigint not null,
    amount numeric(18,2) not null,
    charged_on date not null,
    auto boolean not null,
    invoice_id bigint,
    invoice_number character varying(60),
    charged_by character varying(120),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_late_fee_pkey primary key (id),
    constraint pm_late_fee_rent_charge_id_key unique (rent_charge_id)
);
