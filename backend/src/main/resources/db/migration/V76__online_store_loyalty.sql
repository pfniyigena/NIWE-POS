-- v1.40.0: loyalty points for signed-in shop customers. A customer earns points when an order is completed (a share of what they paid for the goods)
-- and spends them at checkout as a discount (1 point = 1 unit of the shop's currency). Every change of a balance is a row in shop_loyalty_entry, so a balance
-- can always be explained; the balance itself is kept on the account for a quick, lockable check at checkout.

alter table online_store_settings add column loyalty_enabled boolean not null default false;
alter table online_store_settings add column loyalty_points_per100 integer not null default 1;
alter table online_store_settings add column loyalty_max_percent integer not null default 50;

alter table shop_customer add column loyalty_points integer not null default 0;

alter table online_order add column loyalty_points_used integer not null default 0;
alter table online_order add column loyalty_discount numeric(14,2) not null default 0;
alter table online_order add column loyalty_points_earned integer not null default 0;

create table shop_loyalty_entry (
    id bigint generated by default as identity,
    shop_customer_id bigint not null,
    kind varchar(10) not null,
    points integer not null,
    balance_after integer not null,
    online_order_id bigint,
    online_return_id bigint,
    order_code varchar(20),
    note varchar(200),
    created_by varchar(80),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint shop_loyalty_entry_pkey primary key (id),
    constraint shop_loyalty_entry_kind_ck check (kind in ('EARN', 'SPEND', 'SPEND_BACK', 'RET_BACK', 'RET_TAKE', 'ADJUST'))
);
create index shop_loyalty_entry_customer_idx on shop_loyalty_entry (shop_customer_id, id);
-- An order earns once, spends once and gives its points back once; a return restores and takes back once. The database refuses a second row.
create unique index shop_loyalty_entry_order_kind_uk on shop_loyalty_entry (online_order_id, kind) where online_order_id is not null and online_return_id is null;
create unique index shop_loyalty_entry_return_kind_uk on shop_loyalty_entry (online_return_id, kind) where online_return_id is not null;
