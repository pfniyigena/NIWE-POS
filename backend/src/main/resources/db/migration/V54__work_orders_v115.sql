alter table work_order add column approval_required boolean default false not null;
alter table work_order add column approval_status character varying(20) default 'NONE' not null;
alter table work_order add column approval_requested_at timestamp(6) with time zone;
alter table work_order add column approval_decided_at timestamp(6) with time zone;
alter table work_order add column approval_by_name character varying(200);
alter table work_order add column approval_note character varying(1000);
alter table work_order add column approval_recorded_by character varying(255);
alter table work_order add column approval_estimate_total numeric(18,2);
alter table work_order add column estimated_hours numeric(10,2);
alter table work_order add column completion_emailed_at timestamp(6) with time zone;
alter table work_order add column schedule_id bigint;
alter table work_order add constraint work_order_approval_status_check check (approval_status in ('NONE', 'REQUESTED', 'APPROVED', 'REJECTED'));
create index idx_work_order_schedule on work_order using btree (schedule_id);

create table work_order_note (
    id bigint generated by default as identity not null,
    work_order_id bigint not null,
    author_user_id bigint,
    author_name character varying(255),
    text character varying(2000) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint work_order_note_pkey primary key (id)
);
create index idx_work_order_note_wo on work_order_note using btree (work_order_id);

create table work_order_attachment (
    id bigint generated by default as identity not null,
    work_order_id bigint not null,
    file_name character varying(255) not null,
    content_type character varying(100) not null,
    size_bytes bigint not null,
    caption character varying(300),
    uploaded_by_name character varying(255),
    data bytea not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint work_order_attachment_pkey primary key (id)
);
create index idx_work_order_attachment_wo on work_order_attachment using btree (work_order_id);

create table work_order_settings (
    id bigint generated by default as identity not null,
    require_approval_default boolean default false not null,
    email_customer_on_complete boolean default false not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint work_order_settings_pkey primary key (id)
);

create table maintenance_schedule (
    id bigint generated by default as identity not null,
    title character varying(255) not null,
    description character varying(4000),
    item_description character varying(500),
    type character varying(20) not null,
    priority character varying(20) not null,
    customer_id bigint,
    customer_name character varying(255),
    asset_id bigint,
    asset_name character varying(255),
    package_id bigint,
    package_name character varying(255),
    assigned_to_user_id bigint,
    assigned_to_name character varying(255),
    fixed_price numeric(18,2) default 0 not null,
    labour_rate numeric(18,2),
    branch_id bigint,
    interval_unit character varying(10) not null,
    interval_count integer not null,
    next_due_date date not null,
    lead_days integer default 0 not null,
    due_after_days integer default 0 not null,
    skip_if_open boolean default true not null,
    active boolean default true not null,
    last_generated_at timestamp(6) with time zone,
    last_work_order_id bigint,
    times_generated integer default 0 not null,
    created_by_name character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint maintenance_schedule_pkey primary key (id),
    constraint maintenance_schedule_type_check check (type in ('CUSTOMER', 'INTERNAL')),
    constraint maintenance_schedule_priority_check check (priority in ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    constraint maintenance_schedule_unit_check check (interval_unit in ('DAYS', 'WEEKS', 'MONTHS'))
);
create index idx_maintenance_schedule_due on maintenance_schedule using btree (active, next_due_date);
