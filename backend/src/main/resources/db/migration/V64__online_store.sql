-- v1.27.0 Online Store (phase 1): settings, the products shown online, delivery areas, and the orders customers place on the public shop.

create table online_store_settings (
    id bigint generated by default as identity not null,
    enabled boolean not null default false,
    paused boolean not null default false,
    pause_message character varying(200),
    shop_name character varying(120),
    intro_text character varying(300),
    contact_phone character varying(40),
    pickup_address character varying(240),
    pickup_enabled boolean not null default true,
    delivery_enabled boolean not null default true,
    cod_enabled boolean not null default true,
    stock_buffer integer not null default 1,
    min_order numeric(38,2) not null default 0,
    free_delivery_over numeric(38,2),
    max_pending_per_phone integer not null default 3,
    max_per_ip_per_hour integer not null default 20,
    delivery_product_id bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_store_settings_pkey primary key (id)
);

create table online_listing (
    id bigint generated by default as identity not null,
    product_id bigint not null,
    listed boolean not null default true,
    web_title character varying(160),
    web_description text,
    online_price numeric(38,2),
    sort_order integer not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_listing_pkey primary key (id),
    constraint online_listing_product_fk foreign key (product_id) references product (id) on delete cascade
);
create unique index online_listing_product_uq on online_listing (product_id);

create table online_delivery_zone (
    id bigint generated by default as identity not null,
    name character varying(80) not null,
    fee numeric(38,2) not null default 0,
    min_order numeric(38,2) not null default 0,
    active boolean not null default true,
    sort_order integer not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_delivery_zone_pkey primary key (id)
);

create table online_order (
    id bigint generated by default as identity not null,
    code character varying(12) not null,
    status character varying(20) not null default 'PLACED',
    delivery_method character varying(10) not null,
    payment_method character varying(10) not null default 'COD',
    customer_name character varying(80) not null,
    customer_phone character varying(40) not null,
    customer_email character varying(160),
    customer_address character varying(240),
    zone_id bigint,
    zone_name character varying(80),
    delivery_fee numeric(38,2) not null default 0,
    notes character varying(300),
    subtotal numeric(38,2) not null default 0,
    total numeric(38,2) not null default 0,
    language character varying(2) not null default 'en',
    customer_id bigint,
    sales_order_id bigint,
    sales_order_number character varying(40),
    invoice_id bigint,
    invoice_number character varying(40),
    decided_at timestamp(6) with time zone,
    decided_by character varying(80),
    reject_reason character varying(160),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_order_pkey primary key (id)
);
create unique index online_order_code_uq on online_order (code);
create index online_order_status_idx on online_order (status, created_at);

create table online_order_line (
    id bigint generated by default as identity not null,
    online_order_id bigint not null,
    product_id bigint not null,
    name character varying(160) not null,
    quantity numeric(38,4) not null,
    base_price numeric(38,2) not null default 0,
    unit_price numeric(38,2) not null default 0,
    line_total numeric(38,2) not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_order_line_pkey primary key (id),
    constraint online_order_line_order_fk foreign key (online_order_id) references online_order (id) on delete cascade
);

create table online_order_event (
    id bigint generated by default as identity not null,
    online_order_id bigint not null,
    status character varying(20) not null,
    note character varying(200),
    by_user character varying(80),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_order_event_pkey primary key (id),
    constraint online_order_event_order_fk foreign key (online_order_id) references online_order (id) on delete cascade
);
create index online_order_event_order_idx on online_order_event (online_order_id, created_at);
