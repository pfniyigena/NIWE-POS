-- PO-2: cash control at the till: paid in / paid out / safe drops, mid-shift counts, denomination count and variance note at close.
create table pos_settings (
    id bigint generated by default as identity not null,
    variance_tolerance numeric(38,2) not null default 0,
    variance_note_required boolean not null default false,
    denomination_count_required boolean not null default false,
    paid_out_approval_over numeric(38,2) not null default 0,
    drop_alert_amount numeric(38,2) not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pos_settings_pkey primary key (id)
);

create table cash_movement (
    id bigint generated by default as identity not null,
    register_session_id bigint not null,
    cashier_session_id bigint,
    kind character varying(12) not null,
    reason_code character varying(24),
    amount numeric(38,2) not null,
    expected_cash numeric(38,2),
    variance numeric(38,2),
    note character varying(200),
    count_detail text,
    by_user character varying(80),
    approved_by character varying(80),
    voided boolean not null default false,
    void_reason character varying(200),
    voided_by character varying(80),
    voided_at timestamp(6) with time zone,
    branch_id bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint cash_movement_pkey primary key (id),
    constraint cash_movement_session_fk foreign key (register_session_id) references register_session (id)
);
create index cash_movement_session_idx on cash_movement (register_session_id);
create index cash_movement_created_idx on cash_movement (created_at);

alter table register_session add column expected_cash numeric(38,2);
alter table register_session add column variance_note character varying(300);
alter table register_session add column closed_by character varying(80);
alter table register_session add column count_detail text;
