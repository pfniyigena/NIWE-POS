    note character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint expense_budget_pkey primary key (id),
    constraint expense_budget_one_target check ((account_id is not null and cost_center_id is null) or (account_id is null and cost_center_id is not null)),
    constraint expense_budget_amount_check check (monthly_amount > 0)
);
alter table expense_budget add constraint fk_expense_budget_account foreign key (account_id) references account(id);
