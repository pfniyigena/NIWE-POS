-- v1.10.0: "Allow public website" switches for Help Desk and Reserve a Table (Appointments already had one), and the colour theme saved in the database.
alter table help_desk_settings add column public_enabled boolean not null default true;
alter table restaurant_settings add column public_enabled boolean not null default true;

create table user_theme (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null,
    updated_at timestamptz,
    app_user_id bigint not null unique,
    theme varchar(20) not null,
    custom_bg varchar(7),
    custom_accent varchar(7)
);

create table site_theme (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null,
    updated_at timestamptz,
    theme varchar(20) not null,
    custom_bg varchar(7),
    custom_accent varchar(7)
);
