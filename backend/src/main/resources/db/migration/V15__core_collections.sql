-- Customer collections: settings of the reminder run (off until an admin switches it on) and a log of every reminder / statement mailed to a customer.
create table collection_settings (
    id bigint generated by default as identity not null,
    auto_enabled boolean default false not null,
    first_days integer default 1 not null,
    repeat_days integer default 7 not null,
    max_reminders integer default 3 not null,
    default_term_days integer default 30 not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint collection_settings_pkey primary key (id)
);

create table collection_reminder (
    id bigint generated by default as identity not null,
    customer_id bigint not null,
    kind character varying(12) not null,
    to_email character varying(255),
    items integer default 0 not null,
    amount numeric(18,2) default 0 not null,
    sent_by character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint collection_reminder_pkey primary key (id),
    constraint fk_collection_reminder_customer foreign key (customer_id) references customer (id)
);
create index ix_collection_reminder_customer on collection_reminder (customer_id, created_at);
