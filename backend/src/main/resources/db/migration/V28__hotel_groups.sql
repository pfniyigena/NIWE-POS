-- HO-4: group bookings — a named group with room blocks (held rooms with a release date), a rooming list of ordinary bookings,
-- an optional master account (the group pays), and group deposits.

create table hotel_group (
    id bigint generated by default as identity not null,
    group_code character varying(20),
    name character varying(150) not null,
    contact_name character varying(150),
    contact_phone character varying(50),
    contact_email character varying(150),
    contact_guest_id bigint,
    company_id bigint,
    arrival_date date not null,
    departure_date date not null,
    status character varying(12) not null default 'TENTATIVE',
    billing character varying(12) not null default 'INDIVIDUAL',
    notes text,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint hotel_group_pkey primary key (id),
    constraint hotel_group_code_key unique (group_code),
    constraint hotel_group_guest_fk foreign key (contact_guest_id) references guest (id),
    constraint hotel_group_company_fk foreign key (company_id) references customer (id),
    constraint hotel_group_status_check check (status in ('TENTATIVE', 'CONFIRMED', 'CANCELLED', 'COMPLETED')),
    constraint hotel_group_billing_check check (billing in ('INDIVIDUAL', 'MASTER_ROOMS', 'MASTER_ALL'))
);

-- Rooms of one type held for a group on [start_date, end_date), until released (on release_date, or by hand).
create table group_block (
    id bigint generated by default as identity not null,
    group_id bigint not null,
    room_type_id bigint not null,
    rooms integer not null,
    rate numeric(19,2),
    start_date date not null,
    end_date date not null,
    release_date date,
    released boolean not null default false,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint group_block_pkey primary key (id),
    constraint group_block_group_fk foreign key (group_id) references hotel_group (id) on delete cascade,
    constraint group_block_type_fk foreign key (room_type_id) references room_type (id)
);
create index group_block_group_idx on group_block (group_id);

alter table hotel_booking add column group_id bigint;
alter table hotel_booking add constraint hotel_booking_group_fk foreign key (group_id) references hotel_group (id);
create index hotel_booking_group_idx on hotel_booking (group_id);

-- A bill of a stay can be billed to the stay's group instead of the guest.
alter table booking_bill add column to_group boolean not null default false;

-- The group's master account: bills from members at check-out, deposits and payments from the organiser.
create table group_entry (
    id bigint generated by default as identity not null,
    group_id bigint not null,
    kind character varying(10) not null,
    booking_id bigint,
    bill_no integer,
    description character varying(255),
    amount numeric(19,2) not null,
    method character varying(50),
    reference character varying(100),
    entry_date date not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint group_entry_pkey primary key (id),
    constraint group_entry_group_fk foreign key (group_id) references hotel_group (id),
    constraint group_entry_booking_fk foreign key (booking_id) references hotel_booking (id),
    constraint group_entry_kind_check check (kind in ('BILL', 'DEPOSIT', 'APPLIED', 'PAYMENT', 'REFUND'))
);
create index group_entry_group_idx on group_entry (group_id);
