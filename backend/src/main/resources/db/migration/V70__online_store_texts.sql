-- v1.32.0: Online Store phase 3 (3 of 4), text messages (SMS / WhatsApp).
-- A provider (the built-in test sender now, a real one later) delivers the texts; every text the shop sends or skips is logged.
-- Nothing is sent to a customer who did not tick the box at checkout, except the sign-in codes they asked for.

alter table online_store_settings add column text_provider varchar(30);
alter table online_store_settings add column text_channel varchar(10) not null default 'SMS';
alter table online_store_settings add column text_country_code varchar(4) not null default '250';
alter table online_store_settings add column text_daily_limit integer not null default 300;
alter table online_store_settings add column notify_phone varchar(40);

alter table online_order add column text_opt_in boolean not null default false;
alter table online_order add column phone_key varchar(9);
update online_order set phone_key = right(regexp_replace(customer_phone, '[^0-9]', '', 'g'), 9) where customer_phone is not null;
create index online_order_phone_key_idx on online_order (phone_key, created_at) where phone_key is not null;

-- The log of texts. The body is kept so the shop can see what was sent (sign-in codes are logged without the code).
create table online_text_message (
    id bigint generated by default as identity,
    channel varchar(10) not null,
    to_phone varchar(24) not null,
    purpose varchar(20) not null,
    body varchar(400) not null,
    status varchar(10) not null,
    provider varchar(30),
    provider_ref varchar(80),
    error varchar(240),
    online_order_id bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_text_message_pkey primary key (id),
    constraint online_text_message_status_ck check (status in ('SENT', 'FAILED', 'SKIPPED'))
);
create index online_text_message_created_idx on online_text_message (created_at desc);
create index online_text_message_day_idx on online_text_message (created_at) where status = 'SENT';

-- Accounts can now be opened with a phone number proved by a text message. An account has an e-mail address, a verified phone number, or both.
alter table shop_customer alter column email drop not null;
alter table shop_customer add column phone_key varchar(9);
alter table shop_customer add column phone_verified boolean not null default false;
update shop_customer set phone_key = right(regexp_replace(phone, '[^0-9]', '', 'g'), 9) where phone is not null;
create unique index shop_customer_phone_verified_uq on shop_customer (phone_key) where phone_verified;
alter table shop_customer add constraint shop_customer_identity_ck check (email is not null or phone_verified);

-- A sign-in code belongs to an identifier: an e-mail address, or a phone number in international form.
alter table shop_login_code rename column email to identifier;
alter index shop_login_code_email_idx rename to shop_login_code_identifier_idx;
