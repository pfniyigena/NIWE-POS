-- Property Management phase PM-18: a property can have several owners.
-- The owners of a property are kept as a "split": the owners and the percentage each one has, from a date. A property can have several splits
-- over time (when a part is sold, say); the rent paid on a day is shared by the split that was in force that day. valid_from empty = from the
-- beginning. Exactly one owner of each split is the lead (the one the agency deals with; rounding cents go to them). pm_property.owner_id keeps
-- the lead owner of the latest split, so everything that already reads it still works. Every property starts with its owner at 100%.

create table pm_property_owner (
    id bigint generated by default as identity not null,
    property_id bigint not null,
    owner_id bigint not null,
    share_percent numeric(7,2) not null,
    valid_from date,
    lead_owner boolean not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_property_owner_pkey primary key (id)
);

create index idx_pm_property_owner_property on pm_property_owner using btree (property_id);

create index idx_pm_property_owner_owner on pm_property_owner using btree (owner_id);

create unique index uq_pm_property_owner_split on pm_property_owner using btree (property_id, owner_id, coalesce(valid_from, date '0001-01-01'));

insert into pm_property_owner (property_id, owner_id, share_percent, valid_from, lead_owner, created_at)
select id, owner_id, 100, null, true, now() from pm_property;
