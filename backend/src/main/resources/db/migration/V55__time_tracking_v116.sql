create table time_project_member (
    id bigint generated by default as identity not null,
    project_id bigint not null,
    user_id bigint not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint time_project_member_pkey primary key (id),
    constraint uk_time_project_member unique (project_id, user_id)
);
create index idx_time_project_member_user on time_project_member using btree (user_id);
