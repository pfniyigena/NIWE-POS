-- HO-3: split bills, bills to companies (city ledger), cancellation / no-show / early-departure / late check-out fees.

-- Every line and payment belongs to one numbered bill of the stay (bill 1 unless the front desk splits the folio).
alter table folio_charge add column bill_no integer not null default 1;
alter table folio_payment add column bill_no integer not null default 1;
alter table hotel_booking add column room_bill_no integer not null default 1;

-- Fees are their own kind of line so reports can tell them from minibar and laundry.
alter table folio_charge drop constraint folio_charge_charge_type_check;
alter table folio_charge add constraint folio_charge_charge_type_check
    check (charge_type in ('ROOM', 'RESTAURANT', 'POS', 'ROOM_SERVICE', 'EXTRA', 'FEE'));

-- The policy. Everything defaults to "no fee" so existing hotels behave exactly as before.
alter table hotel_settings add column cancel_free_days integer not null default 0;
alter table hotel_settings add column cancel_fee_nights integer not null default 0;
alter table hotel_settings add column no_show_fee_nights integer not null default 0;
alter table hotel_settings add column early_departure_fee_nights integer not null default 0;
alter table hotel_settings add column late_checkout_from character varying(5);
alter table hotel_settings add column late_checkout_percent numeric(5,2) not null default 0;
alter table hotel_settings add column tax_on_fees boolean not null default false;

-- A named bill of a stay: bill 1 is the default; others are added when the folio is split. A bill can be sent to a company.
create table booking_bill (
    id bigint generated by default as identity not null,
    booking_id bigint not null,
    bill_no integer not null,
    label character varying(100),
    company_id bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint booking_bill_pkey primary key (id),
    constraint booking_bill_booking_fk foreign key (booking_id) references hotel_booking (id) on delete cascade,
    constraint booking_bill_company_fk foreign key (company_id) references customer (id),
    constraint booking_bill_unique unique (booking_id, bill_no)
);

-- What a company owes the hotel (the city ledger), created at check-out for each bill sent to a company.
create table company_bill (
    id bigint generated by default as identity not null,
    bill_number character varying(30),
    company_id bigint not null,
    booking_id bigint not null,
    bill_no integer not null,
    description character varying(255),
    amount numeric(19,2) not null,
    paid numeric(19,2) not null default 0,
    status character varying(10) not null default 'OPEN',
    issued_on date not null,
    due_date date,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint company_bill_pkey primary key (id),
    constraint company_bill_number_key unique (bill_number),
    constraint company_bill_company_fk foreign key (company_id) references customer (id),
    constraint company_bill_booking_fk foreign key (booking_id) references hotel_booking (id),
    constraint company_bill_status_check check (status in ('OPEN', 'PAID'))
);
create index company_bill_company_idx on company_bill (company_id, status);

create table company_receipt (
    id bigint generated by default as identity not null,
    company_bill_id bigint not null,
    method character varying(50) not null,
    amount numeric(19,2) not null,
    reference character varying(100),
    received_on date not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint company_receipt_pkey primary key (id),
    constraint company_receipt_bill_fk foreign key (company_bill_id) references company_bill (id)
);
