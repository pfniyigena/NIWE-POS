-- v1.17.0 Booking: reminder e-mails, guest rescheduling, per-person working hours and leave.
alter table booking_settings add column reminder_enabled boolean default false not null;
alter table booking_settings add column reminder_hours integer default 24 not null;
alter table booking_settings add column allow_guest_reschedule boolean default true not null;
alter table booking_settings add column max_guest_reschedules integer default 2 not null;

alter table appointment add column reminder_sent_at timestamp(6) with time zone;
alter table appointment add column reschedule_count integer default 0 not null;
create index idx_appointment_customer on appointment using btree (customer_id);

create table booking_staff_hours (
    id bigint generated by default as identity not null,
    user_id bigint not null,
    weekday integer not null,
    start_time time(6) without time zone not null,
    end_time time(6) without time zone not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint booking_staff_hours_pkey primary key (id),
    constraint uk_booking_staff_hours unique (user_id, weekday)
);

create table booking_staff_leave (
    id bigint generated by default as identity not null,
    user_id bigint not null,
    from_date date not null,
    to_date date not null,
    reason character varying(200),
    created_by_name character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint booking_staff_leave_pkey primary key (id)
);
create index idx_booking_staff_leave_user on booking_staff_leave using btree (user_id, from_date);
