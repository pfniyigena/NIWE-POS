-- HR-8: reversing an approved or paid payroll, and final pay for people who leave.

-- Leave types whose unused days are paid out when an employee leaves (annual leave by default).
alter table leave_type add column payout_on_exit boolean not null default false;
update leave_type set payout_on_exit = true where lower(name) = 'annual leave';

-- Where a payroll adjustment came from (FINAL_PAY = made by the final-pay screen, null = entered by hand).
alter table payroll_adjustment add column source character varying(20);

-- A loan can be set to be taken back in full from one payroll month (the leaver's last).
alter table staff_loan add column settle_year integer;
alter table staff_loan add column settle_month integer;

-- History of what happened to a payroll after it was approved.
alter table payroll_run add column reopened_count integer not null default 0;

create table payroll_run_event (
    id bigint generated by default as identity not null,
    run_id bigint not null,
    kind character varying(24) not null,
    note character varying(300),
    by_name character varying(120),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint payroll_run_event_pkey primary key (id),
    constraint payroll_run_event_run_fk foreign key (run_id) references payroll_run (id) on delete cascade
);
create index payroll_run_event_run_idx on payroll_run_event (run_id);

-- What was worked out for a leaver (one per employee).
create table employee_final_pay (
    id bigint generated by default as identity not null,
    employee_id bigint not null,
    period_year integer not null,
    period_month integer not null,
    last_day date not null,
    daily_rate numeric(19,2) not null,
    leave_days numeric(8,2) not null default 0,
    leave_amount numeric(19,2) not null default 0,
    notice_pay_days numeric(8,2) not null default 0,
    notice_pay_amount numeric(19,2) not null default 0,
    notice_recover_days numeric(8,2) not null default 0,
    notice_recover_amount numeric(19,2) not null default 0,
    settle_loans boolean not null default false,
    note character varying(300),
    created_by_name character varying(120),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint employee_final_pay_pkey primary key (id),
    constraint employee_final_pay_employee_uk unique (employee_id),
    constraint employee_final_pay_employee_fk foreign key (employee_id) references employee (id)
);
