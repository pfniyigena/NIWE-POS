-- v1.30.0: Online Store phase 3a, customer accounts. Sign-in with a one-time code sent to the customer's e-mail; no passwords.

alter table online_store_settings add column accounts_enabled boolean not null default false;

create table shop_customer (
    id bigint generated by default as identity not null,
    email character varying(160) not null,
    phone character varying(40),
    name character varying(80),
    address character varying(240),
    language character varying(5) not null default 'en',
    last_login_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint shop_customer_pkey primary key (id),
    constraint shop_customer_email_uq unique (email)
);
create index shop_customer_phone_idx on shop_customer (phone) where phone is not null;

-- One row per code sent. Only a hash of the code is kept; a code lives 10 minutes and dies after 5 wrong tries.
create table shop_login_code (
    id bigint generated by default as identity not null,
    email character varying(160) not null,
    code_hash character varying(64) not null,
    expires_at timestamp(6) with time zone not null,
    attempts integer not null default 0,
    used boolean not null default false,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint shop_login_code_pkey primary key (id)
);
create index shop_login_code_email_idx on shop_login_code (email, created_at);

-- A signed-in browser. Only a hash of the token is kept.
create table shop_session (
    id bigint generated by default as identity not null,
    shop_customer_id bigint not null,
    token_hash character varying(64) not null,
    expires_at timestamp(6) with time zone not null,
    last_used_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint shop_session_pkey primary key (id),
    constraint shop_session_token_uq unique (token_hash),
    constraint shop_session_customer_fk foreign key (shop_customer_id) references shop_customer (id) on delete cascade
);

alter table online_order add column shop_customer_id bigint;
alter table online_order add constraint online_order_shop_customer_fk foreign key (shop_customer_id) references shop_customer (id) on delete set null;
create index online_order_shop_customer_idx on online_order (shop_customer_id, created_at) where shop_customer_id is not null;
create index online_order_email_idx on online_order (lower(customer_email)) where customer_email is not null;
