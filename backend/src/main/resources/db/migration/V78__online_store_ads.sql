-- v1.43.0: advertising on the online store: advertisers (other businesses), their ads (picture + link + dates + what they pay) and daily view/click counts.
create table online_advertiser (
    id bigint generated by default as identity not null,
    name varchar(120) not null,
    contact_name varchar(120),
    email varchar(160),
    phone varchar(40),
    notes varchar(500),
    active boolean not null default true,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_advertiser_pkey primary key (id)
);

create table online_ad (
    id bigint generated by default as identity not null,
    advertiser_id bigint not null,
    title varchar(120) not null,
    placements varchar(60) not null,
    link_url varchar(500) not null,
    alt_text varchar(160),
    file_name varchar(200) not null,
    content_type varchar(100) not null,
    size_bytes bigint not null,
    data bytea not null,
    starts_on date,
    ends_on date,
    active boolean not null default true,
    fee numeric(14,2),
    fee_note varchar(160),
    fee_paid boolean not null default false,
    sort_order integer not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_ad_pkey primary key (id),
    constraint online_ad_advertiser_fk foreign key (advertiser_id) references online_advertiser (id)
);
create index online_ad_advertiser_idx on online_ad (advertiser_id);

create table online_ad_stat (
    ad_id bigint not null,
    day date not null,
    placement varchar(20) not null,
    views bigint not null default 0,
    clicks bigint not null default 0,
    constraint online_ad_stat_pkey primary key (ad_id, day, placement),
    constraint online_ad_stat_ad_fk foreign key (ad_id) references online_ad (id) on delete cascade
);
