-- RS-4: split checks, voids and comps with a log, receipt copies.
alter table restaurant_order add column parent_order_id bigint;
alter table restaurant_order add column check_label character varying(40);
alter table restaurant_order add column print_count integer not null default 0;
alter table restaurant_order add column cancel_reason character varying(200);
alter table restaurant_order add column cancelled_by character varying(100);
alter table restaurant_order_line add column seat integer;
alter table restaurant_order_line add column comped boolean not null default false;

create table restaurant_void_log (
    id bigint generated by default as identity not null,
    entry_type character varying(20) not null,
    order_id bigint,
    order_label character varying(160),
    description character varying(255),
    quantity integer not null default 0,
    amount numeric(38,2) not null default 0,
    reason character varying(200),
    by_user character varying(100),
    approved_by character varying(100),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint restaurant_void_log_pkey primary key (id)
);
create index idx_restaurant_void_log_created on restaurant_void_log(created_at);
