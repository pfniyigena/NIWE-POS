-- Existing subscriptions that were billed before count their invoices as cycles billed.
update subscription s set cycles_billed = (select count(*) from invoice i where i.subscription_id = s.id and i.status <> 'VOID');

create table subscription_event (
    id bigint generated by default as identity not null,
    subscription_id bigint not null,
    kind character varying(30) not null,
    detail text,
    created_by_name character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint subscription_event_pkey primary key (id)
);
alter table subscription_event add constraint fk_subscription_event_subscription foreign key (subscription_id) references subscription(id);
create index idx_subscription_event_subscription on subscription_event using btree (subscription_id);

create table subscription_settings (
    id bigint generated by default as identity not null,
    dunning_enabled boolean default false not null,
    dunning_first_days integer default 3 not null,
    dunning_repeat_days integer default 7 not null,
    dunning_max integer default 3 not null,
    catch_up_max integer default 1 not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint subscription_settings_pkey primary key (id)
);
