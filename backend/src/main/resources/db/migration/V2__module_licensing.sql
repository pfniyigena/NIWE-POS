-- Module licensing (version 1.1.0): which installation this is, the signed license files installed on it, and the requests
-- an admin makes to add a module. See "Module licensing" in README.md.

create table app_installation (
    id bigint generated by default as identity not null,
    installation_id character varying(64) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint app_installation_pkey primary key (id),
    constraint app_installation_installation_id_key unique (installation_id)
);

create table app_license (
    id bigint generated by default as identity not null,
    active boolean not null,
    expires_at date,
    issued_at date not null,
    serial bigint not null,
    customer character varying(255) not null,
    envelope character varying(8000) not null,
    installation_id character varying(64) not null,
    installed_by character varying(255),
    license_id character varying(64) not null,
    modules character varying(1000) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint app_license_pkey primary key (id)
);

create index idx_app_license_serial on app_license using btree (serial);

create table module_request (
    id bigint generated by default as identity not null,
    emailed boolean not null,
    closed_at timestamp(6) with time zone,
    closed_note character varying(255),
    module_key character varying(255) not null,
    note character varying(500),
    requested_by character varying(255) not null,
    status character varying(255) not null check (status in ('PENDING','FULFILLED','WITHDRAWN')),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint module_request_pkey primary key (id)
);

create index idx_module_request_status on module_request using btree (status);
