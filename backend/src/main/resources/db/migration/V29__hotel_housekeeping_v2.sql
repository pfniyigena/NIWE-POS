create table hk_task (
    id bigint generated by default as identity not null,
    room_id bigint not null,
    task_date date not null,
    kind character varying(12) not null,
    status character varying(12) not null default 'OPEN',
    staff_id bigint,
    notes text,
    started_at timestamp(6) with time zone,
    finished_at timestamp(6) with time zone,
    inspected_at timestamp(6) with time zone,
    inspection_result character varying(8),
    inspection_note text,
    attempts integer not null default 1,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint hk_task_pkey primary key (id),
    constraint hk_task_room_fk foreign key (room_id) references room (id),
    constraint hk_task_staff_fk foreign key (staff_id) references hk_staff (id),
    constraint hk_task_room_day_kind_key unique (room_id, task_date, kind),
    constraint hk_task_kind_check check (kind in ('DEPARTURE', 'STAYOVER')),
    constraint hk_task_status_check check (status in ('OPEN', 'IN_PROGRESS', 'DONE', 'SKIPPED'))
);
create index hk_task_date_idx on hk_task (task_date);

create table hk_task_check (
    id bigint generated by default as identity not null,
    task_id bigint not null,
    label character varying(120) not null,
    passed boolean not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint hk_task_check_pkey primary key (id),
    constraint hk_task_check_task_fk foreign key (task_id) references hk_task (id) on delete cascade
);
create index hk_task_check_task_idx on hk_task_check (task_id);

create table lost_found_item (
    id bigint generated by default as identity not null,
    item_no character varying(20),
    description character varying(255) not null,
    found_on date not null,
    room_id bigint,
    location character varying(120),
    found_by character varying(100),
    status character varying(10) not null default 'FOUND',
    guest_id bigint,
    claimed_by character varying(150),
    claimed_on date,
    notes text,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint lost_found_item_pkey primary key (id),
    constraint lost_found_item_no_key unique (item_no),
    constraint lost_found_room_fk foreign key (room_id) references room (id),
    constraint lost_found_guest_fk foreign key (guest_id) references guest (id),
    constraint lost_found_status_check check (status in ('FOUND', 'CLAIMED', 'DISPOSED'))
);

create table minibar_item (
    id bigint generated by default as identity not null,
    name character varying(100) not null,
    price numeric(19,2) not null,
    taxable boolean not null default true,
    active boolean not null default true,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint minibar_item_pkey primary key (id),
    constraint minibar_item_name_key unique (name)
);

create table linen_log (
    id bigint generated by default as identity not null,
    log_date date not null,
    item character varying(100) not null,
    sent integer not null default 0,
    returned integer not null default 0,
    damaged integer not null default 0,
    notes character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint linen_log_pkey primary key (id)
);
create index linen_log_date_idx on linen_log (log_date);
