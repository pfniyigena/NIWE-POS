-- A customer's review of a product bought on a completed order. Shown only after staff approve it.
create table online_review (
    id bigint generated by default as identity,
    online_order_id bigint not null,
    product_id bigint not null,
    product_name varchar(160) not null,
    shop_customer_id bigint,
    reviewer_name varchar(60) not null,
    rating integer not null,
    review_text varchar(1000),
    status varchar(10) not null default 'PENDING',
    moderated_by varchar(80),
    moderated_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_review_pkey primary key (id),
    constraint online_review_order_fk foreign key (online_order_id) references online_order (id) on delete cascade,
    constraint online_review_once_uq unique (online_order_id, product_id),
    constraint online_review_rating_ck check (rating between 1 and 5),
    constraint online_review_status_ck check (status in ('PENDING', 'APPROVED', 'HIDDEN'))
);
create index online_review_product_idx on online_review (product_id, status);
create index online_review_status_idx on online_review (status, created_at);

-- People who asked for the shop's newsletter. Only CONFIRMED addresses (they clicked the link in the e-mail) count.
create table newsletter_subscriber (
    id bigint generated by default as identity,
    email varchar(160) not null,
    language varchar(2) not null default 'en',
    status varchar(12) not null default 'PENDING',
    confirm_hash varchar(64),
    unsubscribe_token varchar(40) not null,
    confirm_sent_at timestamp(6) with time zone,
    confirmed_at timestamp(6) with time zone,
    unsubscribed_at timestamp(6) with time zone,
    source_ip varchar(45),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint newsletter_subscriber_pkey primary key (id),
    constraint newsletter_subscriber_email_uq unique (email),
    constraint newsletter_subscriber_unsub_uq unique (unsubscribe_token),
    constraint newsletter_subscriber_status_ck check (status in ('PENDING', 'CONFIRMED', 'UNSUBSCRIBED'))
);
create index newsletter_subscriber_status_idx on newsletter_subscriber (status);
