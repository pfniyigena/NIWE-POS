-- v1.71.0: money customers pay online is booked when the provider confirms it (Online Customer Deposits, with a clearing account per provider), applied to the
-- sale at delivery, and cleared against the provider's payouts (with their fees) from Online Store > Payments > Payouts.
alter table online_order add column deposit_left numeric(14,2) not null default 0;

create table online_payout (
    id bigint generated by default as identity,
    channel varchar(20) not null,
    gross numeric(14,2) not null,
    fee numeric(14,2) not null default 0,
    net numeric(14,2) not null,
    reference varchar(80),
    note varchar(300),
    paid_on date not null,
    created_by varchar(80),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_payout_pkey primary key (id),
    constraint online_payout_channel_ck check (channel in ('MOBILE_MONEY', 'CARD'))
);
