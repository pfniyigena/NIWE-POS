-- HR-3: one-off payroll adjustments (bonus, arrears, deduction for one month), and staff advances / loans repaid through payroll.
create table payroll_adjustment (
    id bigint generated by default as identity not null,
    employee_id bigint not null,
    kind character varying(12) not null,
    name character varying(120) not null,
    amount numeric(19,2) not null,
    taxable boolean not null default true,
    period_year integer not null,
    period_month integer not null,
    note character varying(300),
    created_by_name character varying(120),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint payroll_adjustment_pkey primary key (id),
    constraint payroll_adjustment_employee_fk foreign key (employee_id) references employee (id),
    constraint payroll_adjustment_kind_check check (kind in ('EARNING', 'DEDUCTION'))
);
create index payroll_adjustment_period_idx on payroll_adjustment (period_year, period_month);
create index payroll_adjustment_employee_idx on payroll_adjustment (employee_id);

create table staff_loan (
    id bigint generated by default as identity not null,
    loan_number character varying(20),
    employee_id bigint not null,
    loan_type character varying(12) not null,
    principal numeric(19,2) not null,
    installment numeric(19,2) not null,
    issue_date date not null,
    first_year integer not null,
    first_month integer not null,
    status character varying(12) not null default 'ACTIVE',
    branch_id bigint,
    note character varying(300),
    created_by_name character varying(120),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint staff_loan_pkey primary key (id),
    constraint staff_loan_number_key unique (loan_number),
    constraint staff_loan_employee_fk foreign key (employee_id) references employee (id),
    constraint staff_loan_type_check check (loan_type in ('ADVANCE', 'LOAN')),
    constraint staff_loan_status_check check (status in ('ACTIVE', 'PAID_OFF', 'CANCELLED'))
);
create index staff_loan_employee_idx on staff_loan (employee_id);

create table staff_loan_repayment (
    id bigint generated by default as identity not null,
    loan_id bigint not null,
    amount numeric(19,2) not null,
    repaid_on date not null,
    source character varying(12) not null,
    run_id bigint,
    note character varying(300),
    created_by_name character varying(120),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint staff_loan_repayment_pkey primary key (id),
    constraint staff_loan_repayment_loan_fk foreign key (loan_id) references staff_loan (id),
    constraint staff_loan_repayment_source_check check (source in ('PAYROLL', 'CASH', 'WRITE_OFF'))
);
create index staff_loan_repayment_loan_idx on staff_loan_repayment (loan_id);
create index staff_loan_repayment_run_idx on staff_loan_repayment (run_id);

alter table payroll_item add column loan_id bigint;
alter table payroll_item drop constraint payroll_item_target_check;
alter table payroll_item add constraint payroll_item_target_check check (target in ('SOCIAL_SECURITY', 'OTHER', 'STAFF_ADVANCE'));
