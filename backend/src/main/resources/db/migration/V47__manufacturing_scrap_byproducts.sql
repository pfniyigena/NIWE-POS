-- MF-4: scrap, actual component use, by-products.
create table bom_by_product (
    id bigint generated by default as identity not null,
    quantity_per_unit integer not null,
    cost_share_percent numeric(38,2) not null default 0,
    bom_id bigint,
    product_id bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint bom_by_product_pkey primary key (id),
    constraint fk_bom_by_product_bom foreign key (bom_id) references bom(id),
    constraint fk_bom_by_product_product foreign key (product_id) references product(id)
);
create index idx_bom_by_product_bom on bom_by_product(bom_id);

alter table manufacturing_order_run add column quantity_scrapped integer not null default 0;
alter table manufacturing_order_run add column scrap_reason varchar(255);
alter table manufacturing_order_run add column scrap_cost numeric(38,2) not null default 0;
alter table manufacturing_order_run add column by_product_credit numeric(38,2) not null default 0;

alter table manufacturing_order_consumption add column planned_quantity integer;

create table manufacturing_order_run_by_product (
    id bigint generated by default as identity not null,
    product_name varchar(255),
    quantity integer not null,
    cost_value numeric(38,2) not null default 0,
    stock_before integer,
    stock_after integer,
    run_id bigint,
    product_id bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint manufacturing_order_run_by_product_pkey primary key (id),
    constraint fk_mo_run_by_product_run foreign key (run_id) references manufacturing_order_run(id),
    constraint fk_mo_run_by_product_product foreign key (product_id) references product(id)
);
create index idx_mo_run_by_product_run on manufacturing_order_run_by_product(run_id);
