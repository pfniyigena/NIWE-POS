-- v1.54.0: "tell me when it is back in stock": a customer leaves an e-mail address and/or a phone number on a sold-out product; the shop tells them once
-- when the product can be sold again (automatically by e-mail / text message, or by staff through WhatsApp from Online Store > Waiting customers).
create table online_stock_alert (
    id bigint generated by default as identity,
    product_id bigint not null,
    product_name varchar(200) not null,
    email varchar(160),
    phone varchar(40),
    language varchar(2) not null default 'en',
    status varchar(10) not null default 'WAITING',
    attempts integer not null default 0,
    notified_at timestamp(6) with time zone,
    notified_by varchar(80),
    source_ip varchar(45),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_stock_alert_pkey primary key (id)
);
create index online_stock_alert_status_idx on online_stock_alert (status, product_id);
