-- HR-7: employee documents (files with an optional expiry date) and onboarding / offboarding checklists.
create table employee_document (
    id bigint generated by default as identity not null,
    employee_id bigint not null,
    name character varying(200) not null,
    category character varying(20) not null default 'OTHER',
    description character varying(1000),
    expiry_date date,
    shared_with_employee boolean not null default false,
    file_name character varying(255) not null,
    content_type character varying(120),
    size_bytes bigint not null,
    uploaded_by_name character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint employee_document_pkey primary key (id),
    constraint employee_document_employee_fk foreign key (employee_id) references employee (id),
    constraint employee_document_category_check check (category in ('CONTRACT', 'ID_DOCUMENT', 'QUALIFICATION', 'PERMIT', 'PAYROLL', 'DISCIPLINARY', 'OTHER'))
);
create index idx_employee_document_employee on employee_document (employee_id);
create index idx_employee_document_expiry on employee_document (expiry_date);

create table employee_document_blob (
    id bigint generated by default as identity not null,
    document_id bigint not null,
    data bytea not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint employee_document_blob_pkey primary key (id),
    constraint employee_document_blob_document_key unique (document_id)
);

create table checklist_template (
    id bigint generated by default as identity not null,
    name character varying(120) not null,
    kind character varying(12) not null,
    description character varying(300),
    active boolean not null default true,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint checklist_template_pkey primary key (id),
    constraint checklist_template_kind_check check (kind in ('ONBOARDING', 'OFFBOARDING'))
);

create table checklist_template_item (
    id bigint generated by default as identity not null,
    template_id bigint not null,
    sort_order integer not null,
    title character varying(200) not null,
    responsible character varying(60),
    due_offset_days integer not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint checklist_template_item_pkey primary key (id),
    constraint checklist_template_item_template_fk foreign key (template_id) references checklist_template (id)
);

create table employee_checklist (
    id bigint generated by default as identity not null,
    employee_id bigint not null,
    template_id bigint,
    name character varying(120) not null,
    kind character varying(12) not null,
    start_date date not null,
    created_by_name character varying(120),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint employee_checklist_pkey primary key (id),
    constraint employee_checklist_employee_fk foreign key (employee_id) references employee (id),
    constraint employee_checklist_kind_check check (kind in ('ONBOARDING', 'OFFBOARDING'))
);
create index idx_employee_checklist_employee on employee_checklist (employee_id);

create table employee_checklist_item (
    id bigint generated by default as identity not null,
    checklist_id bigint not null,
    sort_order integer not null,
    title character varying(200) not null,
    responsible character varying(60),
    due_date date,
    done boolean not null default false,
    done_at timestamp(6) with time zone,
    done_by_name character varying(120),
    note character varying(300),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint employee_checklist_item_pkey primary key (id),
    constraint employee_checklist_item_checklist_fk foreign key (checklist_id) references employee_checklist (id)
);
create index idx_employee_checklist_item_checklist on employee_checklist_item (checklist_id);
