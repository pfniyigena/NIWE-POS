-- v1.44.0: the product page of the online shop: extra pictures (a gallery) and a table of specifications, both written by staff.
create table online_listing_image (
    id bigint generated by default as identity not null,
    listing_id bigint not null,
    file_name varchar(200) not null,
    content_type varchar(100) not null,
    size_bytes bigint not null,
    sort_order integer not null default 0,
    data bytea not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_listing_image_pkey primary key (id),
    constraint online_listing_image_listing_fk foreign key (listing_id) references online_listing (id) on delete cascade
);
create index online_listing_image_listing_idx on online_listing_image (listing_id, sort_order);

-- The specifications as a JSON list of {label, value}; empty when staff wrote none.
alter table online_listing add column specs text;
