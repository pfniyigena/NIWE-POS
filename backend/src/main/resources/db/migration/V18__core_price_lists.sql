-- Price lists (a set of prices, with an across-the-board adjustment), customer groups (a group of customers sharing a price list), and the price a till line was sold at.
create table price_list (
    id bigint generated by default as identity not null,
    name character varying(120) not null,
    description character varying(500),
    adjust_percent numeric(7,2) not null default 0,
    valid_from date,
    valid_to date,
    active boolean not null default true,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint price_list_pkey primary key (id),
    constraint price_list_name_key unique (name)
);

create table price_list_entry (
    id bigint generated by default as identity not null,
    price_list_id bigint not null,
    product_id bigint not null,
    min_quantity integer not null default 1,
    price numeric(19,2) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint price_list_entry_pkey primary key (id),
    constraint price_list_entry_unique unique (price_list_id, product_id, min_quantity),
    constraint price_list_entry_list_fk foreign key (price_list_id) references price_list (id) on delete cascade,
    constraint price_list_entry_product_fk foreign key (product_id) references product (id)
);

create table customer_group (
    id bigint generated by default as identity not null,
    name character varying(120) not null,
    description character varying(500),
    price_list_id bigint,
    active boolean not null default true,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint customer_group_pkey primary key (id),
    constraint customer_group_name_key unique (name),
    constraint customer_group_list_fk foreign key (price_list_id) references price_list (id)
);

alter table customer add column customer_group_id bigint references customer_group (id);
alter table order_line add column list_price numeric(19,2);
alter table order_line add column price_note character varying(160);
