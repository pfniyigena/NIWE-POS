-- v1.51.0: the shop's information pages (Terms, Privacy, Returns, Delivery: staff may rewrite them, a null body means the starter text) and the
-- messages visitors send through the contact form.
create table online_info_page (
    id bigint generated by default as identity,
    slug varchar(20) not null,
    title varchar(120),
    body text,
    published boolean not null default true,
    updated_by varchar(80),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_info_page_pkey primary key (id),
    constraint online_info_page_slug_uq unique (slug)
);
create table online_contact_message (
    id bigint generated by default as identity,
    name varchar(80) not null,
    email varchar(160),
    phone varchar(40),
    subject varchar(120),
    message varchar(2000) not null,
    order_code varchar(20),
    language varchar(2) not null default 'en',
    status varchar(10) not null default 'NEW',
    note varchar(500),
    handled_by varchar(80),
    handled_at timestamp(6) with time zone,
    source_ip varchar(45),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_contact_message_pkey primary key (id),
    constraint online_contact_message_status_ck check (status in ('NEW', 'ANSWERED'))
);
create index online_contact_message_status_idx on online_contact_message (status, created_at);
