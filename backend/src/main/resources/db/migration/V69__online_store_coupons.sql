-- Online Store phase 3 (2 of 4): coupons. A coupon is a code the customer types at checkout: percent off, a fixed amount off, or free delivery.
-- Uses are counted from the orders themselves (rejected and cancelled orders do not count), so a released order frees its use by itself.
create table online_coupon (
    id bigint generated by default as identity,
    code varchar(40) not null,
    description varchar(160),
    type varchar(20) not null,
    value numeric(14,2) not null default 0,
    max_discount numeric(14,2),
    min_order numeric(14,2) not null default 0,
    valid_from date,
    valid_until date,
    max_uses integer,
    once_per_customer boolean not null default true,
    active boolean not null default true,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_coupon_pkey primary key (id),
    constraint online_coupon_code_uq unique (code),
    constraint online_coupon_type_ck check (type in ('PERCENT', 'FIXED', 'FREE_DELIVERY'))
);

alter table online_order add column coupon_id bigint;
alter table online_order add column coupon_code varchar(40);
alter table online_order add column coupon_key varchar(20);
alter table online_order add column discount_amount numeric(14,2) not null default 0;
alter table online_order add column fee_waived numeric(14,2) not null default 0;
alter table online_order add constraint online_order_coupon_fk foreign key (coupon_id) references online_coupon (id) on delete set null;
create index online_order_coupon_idx on online_order (coupon_id, status) where coupon_id is not null;

alter table online_order_line add column discount_amount numeric(14,2) not null default 0;
