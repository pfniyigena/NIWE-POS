-- HO-6 Guest register: VIP / blacklist flags, preferences, birth date and profession on the guest, and ID document uploads.
alter table guest add column vip boolean not null default false;
alter table guest add column blacklisted boolean not null default false;
alter table guest add column blacklist_reason character varying(500);
alter table guest add column preferences text;
alter table guest add column date_of_birth date;
alter table guest add column profession character varying(120);

create table guest_document (
    id bigint generated by default as identity not null,
    guest_id bigint not null,
    doc_type character varying(20) not null,
    name character varying(200) not null,
    doc_number character varying(120),
    expiry_date date,
    file_name character varying(255) not null,
    content_type character varying(120),
    size_bytes bigint not null,
    uploaded_by_name character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint guest_document_pkey primary key (id),
    constraint guest_document_guest_fk foreign key (guest_id) references guest (id),
    constraint guest_document_type_check check (doc_type in ('PASSPORT', 'NATIONAL_ID', 'DRIVING_LICENCE', 'VISA', 'OTHER'))
);
create index idx_guest_document_guest on guest_document using btree (guest_id);

create table guest_document_blob (
    id bigint generated by default as identity not null,
    document_id bigint not null,
    data bytea not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint guest_document_blob_pkey primary key (id),
    constraint guest_document_blob_document_key unique (document_id),
    constraint guest_document_blob_document_fk foreign key (document_id) references guest_document (id) on delete cascade
);

create index idx_guest_id_number on guest using btree (lower(id_number));
create index idx_guest_phone on guest using btree (phone);
