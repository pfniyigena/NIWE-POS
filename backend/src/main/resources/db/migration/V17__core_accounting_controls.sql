-- Accounting controls: the date the books are closed up to, its change log, and bank reconciliations (a statement ticked off against the ledger).
create table accounting_lock (
    id bigint generated by default as identity not null,
    lock_date date,
    updated_by character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint accounting_lock_pkey primary key (id)
);

create table accounting_lock_log (
    id bigint generated by default as identity not null,
    previous_date date,
    new_date date,
    changed_by character varying(255),
    reason character varying(500),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint accounting_lock_log_pkey primary key (id)
);

create table bank_reconciliation (
    id bigint generated by default as identity not null,
    account_id bigint not null,
    statement_date date not null,
    statement_balance numeric(18,2) not null,
    status character varying(10) not null,
    note character varying(500),
    created_by character varying(255),
    completed_by character varying(255),
    completed_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint bank_reconciliation_pkey primary key (id),
    constraint fk_bank_reconciliation_account foreign key (account_id) references account (id)
);
create index ix_bank_reconciliation_account on bank_reconciliation (account_id, statement_date);

create table bank_reconciliation_line (
    id bigint generated by default as identity not null,
    reconciliation_id bigint not null,
    journal_line_id bigint not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint bank_reconciliation_line_pkey primary key (id),
    constraint fk_brl_reconciliation foreign key (reconciliation_id) references bank_reconciliation (id),
    constraint fk_brl_journal_line foreign key (journal_line_id) references journal_entry_line (id),
    constraint uq_brl_journal_line unique (journal_line_id)
);
create index ix_brl_reconciliation on bank_reconciliation_line (reconciliation_id);
