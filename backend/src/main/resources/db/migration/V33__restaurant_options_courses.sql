-- RS-3: item options (sizes, extras, with add-on prices), courses, allergens and quick kitchen notes.
create table restaurant_option_group (
    id bigint generated by default as identity not null,
    menu_item_id bigint not null,
    name character varying(100) not null,
    required boolean not null default false,
    max_select integer not null default 1,
    sort_order integer not null default 0,
    active boolean not null default true,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint restaurant_option_group_pkey primary key (id),
    constraint restaurant_option_group_item_fk foreign key (menu_item_id) references menu_item(id) on delete cascade
);
create index idx_restaurant_option_group_item on restaurant_option_group(menu_item_id);

create table restaurant_option (
    id bigint generated by default as identity not null,
    group_id bigint not null,
    name character varying(100) not null,
    price_delta numeric(38,2) not null default 0,
    sort_order integer not null default 0,
    active boolean not null default true,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint restaurant_option_pkey primary key (id),
    constraint restaurant_option_group_fk foreign key (group_id) references restaurant_option_group(id) on delete cascade
);
create index idx_restaurant_option_group on restaurant_option(group_id);

create table restaurant_order_line_option (
    id bigint generated by default as identity not null,
    line_id bigint not null,
    option_id bigint,
    group_name character varying(100),
    option_name character varying(100) not null,
    price_delta numeric(38,2) not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint restaurant_order_line_option_pkey primary key (id),
    constraint restaurant_order_line_option_line_fk foreign key (line_id) references restaurant_order_line(id) on delete cascade
);
create index idx_restaurant_order_line_option_line on restaurant_order_line_option(line_id);

alter table menu_item add column allergens character varying(200);
alter table menu_item add column default_course integer not null default 1;

alter table restaurant_order_line add column options_price numeric(38,2) not null default 0;
alter table restaurant_order_line add column course integer not null default 1;
alter table restaurant_order_line add column menu_item_id bigint;
alter table restaurant_order_line add column allergens character varying(200);

alter table restaurant_order add column fired_course integer not null default 1;
alter table restaurant_order add column guest_allergens character varying(200);

alter table restaurant_settings add column note_presets character varying(600) not null default 'No onions,No spice,Extra spicy,Well done,Medium,Sauce on the side,Allergy - ask guest';
