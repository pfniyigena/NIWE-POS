-- v1.61.0: delivery time slots. The shop sets daily windows (with a limit of orders each) and days it does not deliver; the customer picks a day and a window.
create table online_delivery_slot (
    id bigint generated by default as identity,
    start_time time not null,
    end_time time not null,
    max_orders integer not null default 0,
    days varchar(7) not null default '1111111',
    active boolean not null default true,
    sort_order integer not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_delivery_slot_pkey primary key (id)
);

create table online_closed_day (
    id bigint generated by default as identity,
    day date not null,
    reason varchar(80),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_closed_day_pkey primary key (id),
    constraint online_closed_day_uk unique (day)
);

alter table online_store_settings add column slots_enabled boolean not null default false;
alter table online_store_settings add column slots_required boolean not null default false;
alter table online_store_settings add column slot_days_ahead integer not null default 7;
alter table online_store_settings add column slot_notice_hours integer not null default 2;

alter table online_order add column slot_date date;
alter table online_order add column slot_start time;
alter table online_order add column slot_end time;
create index online_order_slot_idx on online_order (slot_date, slot_start) where slot_date is not null;
