-- Gift cards (a balance the store owes the customer, paid in advance) and loyalty points (earned on sales, spent at the till).
create table gift_card (
    id bigint generated by default as identity not null,
    code character varying(40) not null,
    initial_amount numeric(19,2) not null,
    balance numeric(19,2) not null,
    status character varying(12) not null default 'ACTIVE',
    customer_id bigint,
    recipient_name character varying(120),
    expires_on date,
    note character varying(300),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint gift_card_pkey primary key (id),
    constraint gift_card_code_key unique (code)
);

create table gift_card_txn (
    id bigint generated by default as identity not null,
    gift_card_id bigint not null,
    txn_type character varying(16) not null,
    amount numeric(19,2) not null,
    balance_after numeric(19,2) not null,
    payment_method character varying(60),
    register_session_id bigint,
    cashier_session_id bigint,
    order_id bigint,
    note character varying(300),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint gift_card_txn_pkey primary key (id),
    constraint gift_card_txn_card_fk foreign key (gift_card_id) references gift_card (id)
);
create index gift_card_txn_card_idx on gift_card_txn (gift_card_id);
create index gift_card_txn_session_idx on gift_card_txn (register_session_id);
create index gift_card_txn_order_idx on gift_card_txn (order_id);

create table loyalty_setting (
    id bigint not null,
    enabled boolean not null default false,
    spend_amount numeric(19,2) not null default 1000,
    points_earned integer not null default 1,
    point_value numeric(19,4) not null default 10,
    min_redeem_points integer not null default 0,
    max_redeem_percent numeric(5,2) not null default 50,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint loyalty_setting_pkey primary key (id)
);
insert into loyalty_setting (id, created_at, updated_at) values (1, now(), now());

create table loyalty_txn (
    id bigint generated by default as identity not null,
    customer_id bigint not null,
    txn_type character varying(16) not null,
    points integer not null,
    balance_after integer not null,
    order_id bigint,
    return_id bigint,
    note character varying(300),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint loyalty_txn_pkey primary key (id)
);
create index loyalty_txn_customer_idx on loyalty_txn (customer_id);
create index loyalty_txn_order_idx on loyalty_txn (order_id);

-- A payment on a sale can be a gift card (which one) or loyalty points (how many).
alter table payment add column gift_card_id bigint;
alter table payment add column points integer;
alter table payment add column reference character varying(60);

-- What a sale earned, and the customer's balance after it (kept so an old receipt still reads right).
alter table sale_order add column loyalty_earned integer;
alter table sale_order add column loyalty_balance integer;

-- A return gives back to the gift card / points that paid for the sale; only the rest leaves the drawer.
alter table sales_return add column gift_card_refund numeric(38,2) not null default 0;
alter table sales_return add column loyalty_refund numeric(38,2) not null default 0;
alter table sales_return add column points_refund integer not null default 0;
