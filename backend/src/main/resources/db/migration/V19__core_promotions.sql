-- Promotions (percent off, amount off, buy X get Y free; for a product, a category or the whole cart; optionally behind a coupon code) and where each one was used.
create table promotion (
    id bigint generated by default as identity not null,
    name character varying(120) not null,
    description character varying(500),
    promo_type character varying(20) not null,
    scope character varying(20) not null,
    target_id bigint,
    value numeric(19,2),
    buy_quantity integer,
    free_quantity integer,
    min_quantity integer not null default 1,
    min_spend numeric(19,2),
    valid_from date,
    valid_to date,
    coupon_code character varying(40),
    max_uses integer,
    max_uses_per_customer integer,
    customer_group_id bigint,
    active boolean not null default true,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint promotion_pkey primary key (id),
    constraint promotion_name_key unique (name),
    constraint promotion_coupon_key unique (coupon_code),
    constraint promotion_group_fk foreign key (customer_group_id) references customer_group (id)
);

create table promotion_use (
    id bigint generated by default as identity not null,
    promotion_id bigint not null,
    order_id bigint not null,
    customer_id bigint,
    amount numeric(19,2) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint promotion_use_pkey primary key (id),
    constraint promotion_use_promotion_fk foreign key (promotion_id) references promotion (id)
);
create index promotion_use_promotion_idx on promotion_use (promotion_id);

alter table order_line add column promo_percent numeric(16,10) not null default 0;
alter table order_line add column promo_note character varying(300);
alter table sale_order add column coupon_codes character varying(500);
alter table sale_order add column promotion_summary text;
