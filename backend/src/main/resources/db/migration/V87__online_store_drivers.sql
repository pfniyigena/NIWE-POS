-- v1.52.0: delivery drivers of the shop and the driver chosen for an order. The name and phone are copied onto the order, so a printed slip and the
-- history stay right when a driver is renamed or removed.
create table online_driver (
    id bigint generated by default as identity,
    name varchar(80) not null,
    phone varchar(40),
    notes varchar(200),
    active boolean not null default true,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_driver_pkey primary key (id)
);
alter table online_order add column driver_id bigint;
alter table online_order add column driver_name varchar(80);
alter table online_order add column driver_phone varchar(40);
alter table online_order add column driver_assigned_at timestamp(6) with time zone;
create index online_order_driver_idx on online_order (driver_id);
