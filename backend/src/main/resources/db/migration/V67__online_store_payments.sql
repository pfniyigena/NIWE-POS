-- v1.29.0: Online Store phase 2, pay online (mobile money or card through one payment provider).

alter table online_store_settings add column online_payments_enabled boolean not null default false;
alter table online_store_settings add column payment_provider character varying(30);
alter table online_store_settings add column payment_expiry_minutes integer not null default 30;

-- payment_method stays COD or ONLINE; payment_status is NONE (cash), AWAITING, FAILED, PAID, REFUND_DUE or REFUNDED.
alter table online_order add column payment_status character varying(20) not null default 'NONE';
alter table online_order add column payment_channel character varying(20);
alter table online_order add column payment_reference character varying(80);
alter table online_order add column paid_amount numeric(38,2);
alter table online_order add column paid_at timestamp(6) with time zone;
alter table online_order add column refunded_at timestamp(6) with time zone;
alter table online_order add column refund_reference character varying(80);
create index online_order_payment_status_idx on online_order (payment_status) where payment_status <> 'NONE';

-- One row per try to pay. "reference" is ours and is what the provider sends back; it is unique.
create table online_payment (
    id bigint generated by default as identity not null,
    online_order_id bigint not null,
    provider character varying(30) not null,
    reference character varying(40) not null,
    provider_reference character varying(80),
    method character varying(20) not null,
    phone character varying(40),
    amount numeric(38,2) not null,
    currency character varying(8) not null,
    status character varying(12) not null default 'PENDING',
    failure_reason character varying(200),
    redirect_url character varying(500),
    paid_at timestamp(6) with time zone,
    last_checked_at timestamp(6) with time zone,
    expires_at timestamp(6) with time zone not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_payment_pkey primary key (id),
    constraint online_payment_reference_uq unique (reference),
    constraint online_payment_order_fk foreign key (online_order_id) references online_order (id) on delete cascade
);
create index online_payment_order_idx on online_payment (online_order_id);
create index online_payment_pending_idx on online_payment (status, expires_at);

-- Every call the provider made to the webhook (valid signature only), kept for disputes and reconciliation.
create table online_payment_webhook (
    id bigint generated by default as identity not null,
    provider character varying(30) not null,
    reference character varying(80),
    outcome character varying(30) not null,
    body text,
    source_ip character varying(64),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_payment_webhook_pkey primary key (id)
);
create index online_payment_webhook_ref_idx on online_payment_webhook (reference);
