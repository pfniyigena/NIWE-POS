-- RS-2: restaurant discounts, service charge, tips and rounding.
create table restaurant_settings (
    id bigint generated by default as identity not null,
    service_charge_percent numeric(5,2) not null default 0,
    service_charge_dine_in boolean not null default true,
    service_charge_takeaway boolean not null default false,
    service_charge_delivery boolean not null default false,
    service_charge_vat_percent numeric(5,2) not null default 0,
    discount_limit_percent numeric(5,2) not null default 10,
    tips_enabled boolean not null default true,
    tip_presets character varying(60) not null default '5,10,15',
    rounding_unit numeric(12,2) not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint restaurant_settings_pkey primary key (id)
);

