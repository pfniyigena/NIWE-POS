-- MF-2: labour and machine time charged to production runs.
alter table routing_operation add column labour_hourly_rate numeric(38,2);

alter table manufacturing_order add column planned_material_cost numeric(38,2) not null default 0;
alter table manufacturing_order add column planned_labour_cost numeric(38,2) not null default 0;
alter table manufacturing_order add column planned_machine_cost numeric(38,2) not null default 0;
alter table manufacturing_order add column planned_overhead_cost numeric(38,2) not null default 0;

alter table manufacturing_order_run add column labour_cost numeric(38,2) not null default 0;
alter table manufacturing_order_run add column machine_cost numeric(38,2) not null default 0;

create table manufacturing_order_operation (
    id bigint generated by default as identity not null,
    sequence integer not null,
    name varchar(255),
    workstation_id bigint,
    workstation_name varchar(255),
    minutes_per_unit numeric(38,2) not null default 0,
    machine_rate numeric(38,2) not null default 0,
    labour_rate numeric(38,2) not null default 0,
    manufacturing_order_id bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint manufacturing_order_operation_pkey primary key (id),
    constraint fk_mo_operation_order foreign key (manufacturing_order_id) references manufacturing_order(id)
);
create index idx_mo_operation_order on manufacturing_order_operation(manufacturing_order_id);

create table manufacturing_order_run_operation (
    id bigint generated by default as identity not null,
    sequence integer not null,
    name varchar(255),
    workstation_id bigint,
    workstation_name varchar(255),
    planned_minutes numeric(38,2) not null default 0,
    actual_minutes numeric(38,2) not null default 0,
    machine_cost numeric(38,2) not null default 0,
    labour_cost numeric(38,2) not null default 0,
    run_id bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint manufacturing_order_run_operation_pkey primary key (id),
    constraint fk_mo_run_operation_run foreign key (run_id) references manufacturing_order_run(id)
);
create index idx_mo_run_operation_run on manufacturing_order_run_operation(run_id);
