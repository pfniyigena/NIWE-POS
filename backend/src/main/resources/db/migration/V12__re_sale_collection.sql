-- Real Estate: the collection notes kept on a unit sale (calls to the buyer, promises to pay, reminders and statements sent).
create table re_sale_note (
    id bigint generated by default as identity not null,
    sale_id bigint not null,
    kind character varying(20) not null,
    text character varying(2000) not null,
    promise_date date,
    created_by_user_id bigint,
    created_by_name character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint re_sale_note_pkey primary key (id)
);
create index idx_re_sale_note_sale on re_sale_note (sale_id);
