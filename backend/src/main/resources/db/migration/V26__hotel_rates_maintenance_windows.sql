-- HO-2: seasonal and special rates, rate plans, per-night prices on a booking, dated maintenance blocks.

-- Rate plans: a named way of selling a room (room only, bed and breakfast, corporate...) that moves the nightly rate by a percent and/or an amount.
create table rate_plan (
    id bigint generated by default as identity not null,
    name character varying(100) not null,
    description text,
    adjust_percent numeric(8,2) not null default 0,
    adjust_amount numeric(19,2) not null default 0,
    min_nights integer not null default 1,
    active boolean not null default true,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint rate_plan_pkey primary key (id),
    constraint rate_plan_name_key unique (name)
);

-- Rate rules: seasons, weekends, long stays. A rule replaces the nightly rate (FIXED) or moves it (PERCENT, AMOUNT) on the nights it covers.
create table rate_rule (
    id bigint generated by default as identity not null,
    name character varying(100) not null,
    room_type_id bigint,
    start_date date not null,
    end_date date,
    days_of_week character varying(40),
    mode character varying(10) not null,
    rule_value numeric(19,2) not null,
    min_nights integer not null default 1,
    priority integer not null default 0,
    active boolean not null default true,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint rate_rule_pkey primary key (id),
    constraint rate_rule_type_fk foreign key (room_type_id) references room_type (id)
);
create index rate_rule_type_idx on rate_rule (room_type_id);

-- What each night of a booking costs (before tax, before any extra-guest charge). Bookings priced by hand (FIXED) have no rows here.
create table hotel_booking_night (
    id bigint generated by default as identity not null,
    booking_id bigint not null,
    night_date date not null,
    rate numeric(19,2) not null,
    rule_name character varying(100),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint hotel_booking_night_pkey primary key (id),
    constraint hotel_booking_night_booking_fk foreign key (booking_id) references hotel_booking (id) on delete cascade,
    constraint hotel_booking_night_key unique (booking_id, night_date)
);

-- AUTO = priced night by night from the rate rules; FIXED = one agreed nightly rate (all bookings made before this version).
alter table hotel_booking add column rate_mode character varying(10) not null default 'FIXED';
alter table hotel_booking add column rate_plan_id bigint;
alter table hotel_booking add constraint hotel_booking_rate_plan_fk foreign key (rate_plan_id) references rate_plan (id);

-- A repair can take the room out of sale for a date window instead of "from now until done".
alter table maintenance_request add column block_from date;
alter table maintenance_request add column block_until date;
