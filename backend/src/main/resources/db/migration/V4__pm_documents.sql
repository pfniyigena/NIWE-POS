-- Property Management phase PM-14: documents attached to properties, units, owners, tenants, leases and repair requests.
-- The bytes live in their own table so lists never read them.

create table pm_document (
    id bigint generated by default as identity not null,
    expiry_date date,
    size_bytes bigint not null,
    subject_id bigint not null,
    category character varying(20) not null,
    subject_type character varying(20) not null,
    content_type character varying(120),
    name character varying(200) not null,
    description character varying(1000),
    file_name character varying(255) not null,
    uploaded_by_name character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_document_pkey primary key (id),
    constraint pm_document_category_check check (category in ('LEASE_AGREEMENT', 'ID_DOCUMENT', 'TITLE_DEED', 'INSPECTION', 'PERMIT', 'INSURANCE', 'PHOTO', 'RECEIPT', 'NOTICE', 'OTHER')),
    constraint pm_document_subject_type_check check (subject_type in ('PROPERTY', 'UNIT', 'OWNER', 'TENANT', 'LEASE', 'MAINTENANCE'))
);

create index idx_pm_document_expiry_date on pm_document using btree (expiry_date);

create index idx_pm_document_subject on pm_document using btree (subject_type, subject_id);

create table pm_document_blob (
    id bigint generated by default as identity not null,
    document_id bigint not null,
    data bytea not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_document_blob_pkey primary key (id),
    constraint pm_document_blob_document_id_key unique (document_id)
);
