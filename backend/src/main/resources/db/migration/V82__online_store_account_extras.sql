-- v1.47.0: saved delivery addresses and a wishlist for signed-in shop customers, and the shop's WhatsApp number.
create table shop_address (
    id bigint generated by default as identity,
    shop_customer_id bigint not null,
    label varchar(60) not null,
    zone_id bigint,
    address varchar(240) not null,
    default_address boolean not null default false,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint shop_address_pkey primary key (id)
);
create index shop_address_customer_idx on shop_address (shop_customer_id, id);

create table shop_wish (
    id bigint generated by default as identity,
    shop_customer_id bigint not null,
    product_id bigint not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint shop_wish_pkey primary key (id),
    constraint shop_wish_once_uq unique (shop_customer_id, product_id)
);

alter table online_store_settings add column whatsapp_number varchar(40);
