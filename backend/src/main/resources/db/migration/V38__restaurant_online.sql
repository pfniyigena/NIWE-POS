create table restaurant_delivery_zone (
    id bigint generated by default as identity not null,
    name character varying(80) not null,
    fee numeric(38,2) not null default 0,
    min_order numeric(38,2) not null default 0,
    extra_minutes integer not null default 0,
    active boolean not null default true,
    sort_order integer not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint restaurant_delivery_zone_pkey primary key (id)
);

create table restaurant_online_order (
    id bigint generated by default as identity not null,
    code character varying(12) not null,
    mode character varying(10) not null,
    status character varying(10) not null default 'PENDING',
    source character varying(10) not null default 'WEB',
    table_id bigint,
    table_name character varying(80),
    customer_name character varying(80) not null,
    customer_phone character varying(40),
    customer_email character varying(160),
    customer_address character varying(240),
    zone_id bigint,
    zone_name character varying(80),
    delivery_fee numeric(38,2) not null default 0,
    notes character varying(300),
    estimated_subtotal numeric(38,2) not null default 0,
    estimated_total numeric(38,2) not null default 0,
    eta_minutes integer,
    decided_at timestamp(6) with time zone,
    decided_by character varying(80),
    reject_reason character varying(120),
    restaurant_order_id bigint,
    restaurant_line_ids character varying(400),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint restaurant_online_order_pkey primary key (id)
);
create unique index restaurant_online_order_code_uq on restaurant_online_order (code);
create index restaurant_online_order_status_idx on restaurant_online_order (status, created_at);

create table restaurant_online_order_line (
    id bigint generated by default as identity not null,
    online_order_id bigint not null,
    menu_item_id bigint not null,
    name character varying(160) not null,
    quantity integer not null,
    notes character varying(200),
    option_ids character varying(200),
    option_names character varying(300),
    unit_price numeric(38,2) not null default 0,
    line_total numeric(38,2) not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint restaurant_online_order_line_pkey primary key (id),
    constraint restaurant_online_order_line_order_fk foreign key (online_order_id) references restaurant_online_order (id) on delete cascade
);
