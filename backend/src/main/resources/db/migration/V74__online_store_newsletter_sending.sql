-- v1.38.0: sending the shop's newsletter from the app. A campaign is the message (subject, text, optional button) and its audience; a delivery is one
-- address of one campaign, made when sending starts, so the list is fixed then and an address can never get the same campaign twice.

create table newsletter_campaign (
    id bigint generated by default as identity,
    subject varchar(160) not null,
    body text not null,
    button_label varchar(60),
    button_link varchar(300),
    audience varchar(3) not null default 'ALL',
    status varchar(10) not null default 'DRAFT',
    recipients integer not null default 0,
    created_by varchar(80),
    started_at timestamp(6) with time zone,
    finished_at timestamp(6) with time zone,
    last_error varchar(200),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint newsletter_campaign_pkey primary key (id),
    constraint newsletter_campaign_status_ck check (status in ('DRAFT', 'SENDING', 'SENT', 'CANCELLED')),
    constraint newsletter_campaign_audience_ck check (audience in ('ALL', 'EN', 'FR'))
);
create index newsletter_campaign_status_idx on newsletter_campaign (status);

create table newsletter_delivery (
    id bigint generated by default as identity,
    campaign_id bigint not null,
    subscriber_id bigint,
    email varchar(160) not null,
    language varchar(2) not null default 'en',
    status varchar(10) not null default 'PENDING',
    error varchar(200),
    sent_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint newsletter_delivery_pkey primary key (id),
    constraint newsletter_delivery_campaign_fk foreign key (campaign_id) references newsletter_campaign (id) on delete cascade,
    constraint newsletter_delivery_subscriber_fk foreign key (subscriber_id) references newsletter_subscriber (id) on delete set null,
    constraint newsletter_delivery_once_uq unique (campaign_id, email),
    constraint newsletter_delivery_status_ck check (status in ('PENDING', 'SENDING', 'SENT', 'FAILED', 'SKIPPED'))
);
create index newsletter_delivery_campaign_idx on newsletter_delivery (campaign_id, status, id);
create index newsletter_delivery_sent_idx on newsletter_delivery (sent_at) where status = 'SENT';
