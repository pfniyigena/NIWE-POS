-- v1.33.0: Online Store phase 3 (4 of 4), returns and refunds after completion.
-- A customer asks to return goods from a completed order; staff approve or refuse; processing puts the goods back in stock through the sale order
-- return (so the books and the reports see it) and gives the money back the way the customer paid.

alter table online_store_settings add column return_window_days integer not null default 14;

-- How much of the money paid online has been given back (all of it after a cancelled paid order, part of it after a partial return).
alter table online_order add column refunded_total numeric(14,2) not null default 0;
update online_order set refunded_total = paid_amount where payment_status = 'REFUNDED' and paid_amount is not null;

create table online_return (
    id bigint generated by default as identity,
    code varchar(24) not null,
    online_order_id bigint not null,
    status varchar(12) not null,
    reason varchar(300) not null,
    staff_note varchar(300),
    decided_at timestamp(6) with time zone,
    decided_by varchar(80),
    refund_amount numeric(14,2) not null default 0,
    refund_method varchar(10),
    refund_reference varchar(80),
    refunded_at timestamp(6) with time zone,
    refunded_by varchar(80),
    sales_order_return_id bigint,
    sales_order_return_number varchar(40),
    location_id bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_return_pkey primary key (id),
    constraint online_return_code_uq unique (code),
    constraint online_return_order_fk foreign key (online_order_id) references online_order (id) on delete cascade,
    constraint online_return_status_ck check (status in ('REQUESTED', 'APPROVED', 'REFUSED', 'REFUNDED')),
    constraint online_return_method_ck check (refund_method is null or refund_method in ('PROVIDER', 'MANUAL', 'CASH'))
);
create index online_return_order_idx on online_return (online_order_id);
create index online_return_status_idx on online_return (status, created_at);

create table online_return_line (
    id bigint generated by default as identity,
    online_return_id bigint not null,
    online_order_line_id bigint not null,
    product_id bigint not null,
    name varchar(160) not null,
    quantity numeric(38,4) not null,
    amount numeric(14,2) not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_return_line_pkey primary key (id),
    constraint online_return_line_return_fk foreign key (online_return_id) references online_return (id) on delete cascade,
    constraint online_return_line_qty_ck check (quantity > 0)
);
create index online_return_line_return_idx on online_return_line (online_return_id);
create index online_return_line_order_line_idx on online_return_line (online_order_line_id);
