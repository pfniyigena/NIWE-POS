-- Property Management phase PM-16: the tax invoice to the owner for the management fee (and the VAT on it) of an agreed owner statement.
-- It is a document, numbered in one running series: the books are posted by the statement, as before. The seller and the owner are copied onto it so that
-- changing a name or tax number later never alters an invoice already issued.

create table pm_fee_invoice (
    id bigint generated by default as identity not null,
    number character varying(20) not null,
    statement_id bigint,
    statement_code character varying(20),
    owner_id bigint not null,
    issue_date date not null,
    period_from date not null,
    period_to date not null,
    status character varying(8) not null,
    net_amount numeric(18,2) not null,
    vat_percent numeric(7,2),
    vat_amount numeric(18,2) not null,
    total_amount numeric(18,2) not null,
    owner_name character varying(200) not null,
    owner_tax_number character varying(80),
    owner_address character varying(500),
    seller_name character varying(255),
    seller_tax_id character varying(80),
    seller_address character varying(500),
    seller_phone character varying(80),
    seller_email character varying(255),
    issued_by_name character varying(255),
    void_reason character varying(500),
    voided_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_fee_invoice_pkey primary key (id),
    constraint pm_fee_invoice_number_key unique (number),
    constraint pm_fee_invoice_status_check check (status in ('ISSUED', 'VOID'))
);

create index idx_pm_fee_invoice_owner on pm_fee_invoice using btree (owner_id);

create index idx_pm_fee_invoice_issue_date on pm_fee_invoice using btree (issue_date);

create index idx_pm_fee_invoice_statement on pm_fee_invoice using btree (statement_id);

-- a statement has at most one invoice in force
create unique index uq_pm_fee_invoice_statement_issued on pm_fee_invoice using btree (statement_id) where status = 'ISSUED';

create table pm_fee_invoice_line (
    id bigint generated by default as identity not null,
    invoice_id bigint not null,
    sort_order integer not null,
    property_id bigint,
    description character varying(300) not null,
    base_amount numeric(18,2),
    fee_percent numeric(7,2),
    net_amount numeric(18,2) not null,
    vat_amount numeric(18,2) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_fee_invoice_line_pkey primary key (id)
);

create index idx_pm_fee_invoice_line_invoice on pm_fee_invoice_line using btree (invoice_id);
