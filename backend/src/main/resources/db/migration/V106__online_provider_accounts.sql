-- v1.76.0: staff choose the accounts each payment provider uses (Online Store > Payments > Accounts by provider).
create table online_provider_account (
    id bigint generated by default as identity,
    provider_code varchar(40) not null,
    clearing_account_id bigint,
    payout_account_id bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint online_provider_account_pkey primary key (id),
    constraint online_provider_account_code_uk unique (provider_code)
);
-- the ledger channel is now the provider's code (it was MTN / AIRTEL in v1.75.0)
update online_order set clearing_channel = 'MTN_MOMO' where clearing_channel = 'MTN';
update online_order set clearing_channel = 'AIRTEL_MONEY' where clearing_channel = 'AIRTEL';
alter table online_payout drop constraint online_payout_channel_ck;
alter table online_payout alter column channel type varchar(40);
update online_payout set channel = 'MTN_MOMO' where channel = 'MTN';
update online_payout set channel = 'AIRTEL_MONEY' where channel = 'AIRTEL';
