-- v1.18.0 Installments: collections follow-ups, early payoff, payment reversal, default and write-off, agreement wording.
alter table installment_plan drop constraint installment_plan_status_check;
alter table installment_plan add constraint installment_plan_status_check check (status in ('ACTIVE', 'COMPLETED', 'CANCELLED', 'DEFAULTED', 'WRITTEN_OFF'));
alter table installment_plan add column defaulted_on date;
alter table installment_plan add column default_reason character varying(255);
alter table installment_plan add column written_off_on date;
alter table installment_plan add column written_off_amount numeric(38,2);
alter table installment_plan add column write_off_reason character varying(255);

alter table installment_payment add column reversed_at timestamp(6) with time zone;
alter table installment_payment add column reversed_by_name character varying(255);
alter table installment_payment add column reverse_reason character varying(255);
alter table installment_payment add column reversal_payment_id bigint;

alter table installment_settings add column payoff_rebate_percent numeric(38,2) default 100 not null;
alter table installment_settings add column default_after_days integer default 0 not null;
alter table installment_settings add column agreement_terms text;

alter table customer_payment add column reversal_of_payment_id bigint;

create table installment_follow_up (
    id bigint generated by default as identity not null,
    plan_id bigint not null,
    kind character varying(255) not null,
    note text,
    promised_on date,
    promised_amount numeric(38,2),
    created_by_name character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint installment_follow_up_pkey primary key (id),
    constraint installment_follow_up_kind_check check (kind in ('CALL', 'VISIT', 'EMAIL', 'PROMISE', 'NOTE'))
);
alter table installment_follow_up add constraint fk_installment_follow_up_plan foreign key (plan_id) references installment_plan(id);
create index idx_installment_follow_up_plan on installment_follow_up using btree (plan_id);
