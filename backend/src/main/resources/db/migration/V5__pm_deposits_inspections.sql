alter table pm_document drop constraint pm_document_subject_type_check;
alter table pm_document add constraint pm_document_subject_type_check check (subject_type in ('PROPERTY', 'UNIT', 'OWNER', 'TENANT', 'LEASE', 'MAINTENANCE', 'INSPECTION'));
