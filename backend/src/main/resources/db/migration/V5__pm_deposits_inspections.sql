-- Property Management phase PM-15: the security deposit of each lease (money in, deductions, refund, transfer to a renewal) and the move-in / move-out inspections.

create table pm_deposit_txn (
    id bigint generated by default as identity not null,
    lease_id bigint not null,
    kind character varying(12) not null,
    amount numeric(18,2) not null,
    txn_date date not null,
    method character varying(40),
    reason character varying(14),
    note character varying(1000),
    invoice_id bigint,
    receipt_number character varying(60),
    other_lease_id bigint,
    other_txn_id bigint,
    voided boolean not null default false,
    void_reason character varying(500),
    voided_at timestamp(6) with time zone,
    recorded_by_name character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_deposit_txn_pkey primary key (id),
    constraint pm_deposit_txn_amount_check check (amount > 0),
    constraint pm_deposit_txn_kind_check check (kind in ('RECEIVED', 'TRANSFER_IN', 'DEDUCTION', 'REFUND', 'TRANSFER_OUT')),
    constraint pm_deposit_txn_reason_check check (reason is null or reason in ('UNPAID_RENT', 'DAMAGE', 'CLEANING', 'UTILITIES', 'OTHER'))
);

create index idx_pm_deposit_txn_lease on pm_deposit_txn using btree (lease_id);

create table pm_inspection (
    id bigint generated by default as identity not null,
    code character varying(20) not null,
    lease_id bigint not null,
    kind character varying(10) not null,
    status character varying(10) not null,
    inspection_date date not null,
    inspector_name character varying(200),
    electricity_reading character varying(40),
    water_reading character varying(40),
    keys_handed integer,
    notes character varying(2000),
    tenant_acknowledged boolean not null default false,
    tenant_signed_name character varying(200),
    signed_off_on date,
    signed_off_by_name character varying(255),
    created_by_name character varying(255),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_inspection_pkey primary key (id),
    constraint pm_inspection_code_key unique (code),
    constraint pm_inspection_kind_check check (kind in ('MOVE_IN', 'MOVE_OUT', 'PERIODIC')),
    constraint pm_inspection_status_check check (status in ('DRAFT', 'SIGNED_OFF'))
);

create index idx_pm_inspection_lease on pm_inspection using btree (lease_id);

create table pm_inspection_item (
    id bigint generated by default as identity not null,
    inspection_id bigint not null,
    sort_order integer not null,
    room character varying(80) not null,
    item character varying(120) not null,
    item_condition character varying(10),
    baseline_condition character varying(10),
    notes character varying(500),
    repair_cost numeric(18,2),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    constraint pm_inspection_item_pkey primary key (id),
    constraint pm_inspection_item_condition_check check (item_condition is null or item_condition in ('GOOD', 'FAIR', 'POOR', 'DAMAGED', 'MISSING', 'NA')),
    constraint pm_inspection_item_baseline_check check (baseline_condition is null or baseline_condition in ('GOOD', 'FAIR', 'POOR', 'DAMAGED', 'MISSING', 'NA')),
    constraint pm_inspection_item_cost_check check (repair_cost is null or repair_cost >= 0)
);

create index idx_pm_inspection_item_inspection on pm_inspection_item using btree (inspection_id);

