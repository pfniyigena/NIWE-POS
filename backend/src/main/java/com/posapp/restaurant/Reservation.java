package com.posapp.restaurant;

import com.posapp.common.BaseEntity;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.ManyToOne;
import lombok.Getter;
import lombok.Setter;

import java.time.Instant;

/**
 * A booking for a future dine-in visit (Fourier: "Reservations") — free-text guest details rather
 * than a link to an existing Customer record, matching a typical reservation book (a party
 * doesn't need to already be a known customer to book a table).
 *
 * <p>Fourier: "Public reservations should show available table for that day. The person then
 * book table. Once Booked it can not be used by anyone. To use the reserved table, you need to
 * enter reservation number. But the reservation can be cancelled anytime by admin." Four
 * consequences of that one sentence live here: {@link #confirmationCode} is the "reservation
 * number" handed back at booking time and later typed in by staff to seat the party (see {@code
 * ReservationService.seatByCode}); {@code table} being set at BOOKED time (checked for
 * once-per-day exclusivity by {@code ReservationService.assertTableAvailable}, not just a later
 * staff decision) is what makes a booked table unusable by anyone else that same day; and {@code
 * ReservationController.cancel} is ADMIN-only, enforced there via {@code @PreAuthorize}.
 */
@Getter
@Setter
@Entity
public class Reservation extends BaseEntity {

    private String guestName;
    private String guestPhone;
    private int partySize = 2;

    private Instant reservedFor;

    /** Nullable until a table is actually assigned — a staff-made reservation can still be taken before deciding which table; a public one always has this set at booking time (see this class's own javadoc). */
    @ManyToOne(fetch = FetchType.LAZY)
    private DiningTable table;

    @Enumerated(EnumType.STRING)
    private ReservationStatus status = ReservationStatus.BOOKED;

    private String notes;

    /** Set once {@code ReservationService.seat} opens a real RestaurantOrder for this booking. */
    private Long restaurantOrderId;

    /** The "reservation number" — generated once at booking time, unique, used later to seat the party (see this class's own javadoc) and never regenerated by {@code update}. */
    @Column(unique = true, length = 16)
    private String confirmationCode;
}
