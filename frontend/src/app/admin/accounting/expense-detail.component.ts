import { Component, OnInit } from '@angular/core';
import { CommonModule } from '@angular/common';
import { FormsModule } from '@angular/forms';
import { ActivatedRoute, RouterLink } from '@angular/router';
import { ShellComponent } from '../../shared/shell.component';
import { ExpenseApiService } from '../../core/api/expense-api.service';
import { Expense } from '../../core/models';

/**
 * Admin > Accounting > Expenses > detail — where a PENDING expense is approved, rejected or
 * edited, where an APPROVED one is voided or (if it posted unpaid) settled, and where its receipt
 * is shown if one was attached. See the backend ExpenseStatus javadoc for the full lifecycle.
 */
@Component({
  selector: 'app-expense-detail',
  standalone: true,
  imports: [CommonModule, FormsModule, RouterLink, ShellComponent],
  template: `
    <app-shell [narrow]="true">
      <div class="alert alert-danger" *ngIf="error">{{ error }}</div>
      <ng-container *ngIf="expense as e">
        <div class="flex justify-between align-center mb-3">
          <div>
            <h3 style="margin-bottom:0.25rem;">{{ e.payeeName }}</h3>
            <span class="badge" [ngClass]="statusClass(e.status)">{{ e.status }}</span>
          </div>
          <div class="flex gap-2">
            <a class="btn btn-outline-primary" *ngIf="e.status === 'PENDING'" [routerLink]="['/admin/accounting/expenses', e.id, 'edit']">Edit</a>
            <button class="btn btn-primary" *ngIf="e.status === 'PENDING'" (click)="approve()">Approve</button>
            <button class="btn btn-outline-danger" *ngIf="e.status === 'PENDING'" (click)="reject()">Reject</button>
            <button class="btn btn-outline-danger" *ngIf="e.status === 'APPROVED' && !e.settledAt" (click)="voidIt()">Void</button>
            <button class="btn btn-outline-primary" *ngIf="e.status === 'APPROVED' && !e.paid && !e.settledAt" (click)="settle()">Record settlement</button>
          </div>
        </div>

        <div class="stat-grid mb-3">
          <div class="stat-tile">
            <div class="stat-label">Date</div>
            <div class="stat-value" style="font-size:1.1rem;">{{ e.expenseDate }}</div>
          </div>
          <div class="stat-tile">
            <div class="stat-label">Category</div>
            <div class="stat-value" style="font-size:1.1rem;">{{ e.accountCode }} — {{ e.accountName }}</div>
          </div>
          <div class="stat-tile">
            <div class="stat-label">Amount</div>
            <div class="stat-value" style="font-size:1.1rem;">{{ e.amount | number: '1.2-2' }}</div>
          </div>
          <div class="stat-tile">
            <div class="stat-label">Payment</div>
            <div class="stat-value" style="font-size:1.1rem;">
              {{ e.paid ? 'Paid from Cash' : (e.settledAt ? 'Bill — settled' : 'Bill — unpaid') }}
            </div>
          </div>
          <div class="stat-tile" *ngIf="e.costCenterName">
            <div class="stat-label">Cost center</div>
            <div class="stat-value" style="font-size:1.1rem;">{{ e.costCenterName }}</div>
          </div>
        </div>

        <p class="text-muted mb-3" *ngIf="e.memo">{{ e.memo }}</p>
        <p class="text-muted mb-3" *ngIf="e.recurringTemplateId">Auto-generated by a recurring expense template.</p>
        <div class="alert alert-danger mb-3" *ngIf="e.status === 'REJECTED' && e.rejectionReason">Rejection reason: {{ e.rejectionReason }}</div>
        <div class="alert alert-danger mb-3" *ngIf="e.status === 'VOIDED' && e.voidReason">Void reason: {{ e.voidReason }}</div>

        <div class="mb-3" *ngIf="e.receiptDataUrl">
          <h4 class="mb-2">Receipt</h4>
          <a [href]="e.receiptDataUrl" target="_blank">
            <img [src]="e.receiptDataUrl" alt="Receipt" style="max-width:260px; border:1px solid var(--border, #444); border-radius:4px;" />
          </a>
        </div>
      </ng-container>
    </app-shell>
  `,
})
export class ExpenseDetailComponent implements OnInit {
  expense: Expense | null = null;
  error: string | null = null;

  constructor(private expenseApi: ExpenseApiService, private route: ActivatedRoute) {}

  ngOnInit(): void {
    this.load();
  }

  load(): void {
    const id = Number(this.route.snapshot.paramMap.get('id'));
    this.expenseApi.getById(id).subscribe({
      next: (e) => (this.expense = e),
      error: (err) => (this.error = err?.error?.message ?? 'Failed to load expense'),
    });
  }

  approve(): void {
    if (!this.expense) return;
    this.error = null;
    this.expenseApi.approve(this.expense.id).subscribe({
      next: () => this.load(),
      error: (err) => (this.error = err?.error?.message ?? 'Failed to approve expense'),
    });
  }

  reject(): void {
    if (!this.expense) return;
    const reason = prompt('Reason for rejecting (optional):') ?? '';
    this.error = null;
    this.expenseApi.reject(this.expense.id, reason || null).subscribe({
      next: () => this.load(),
      error: (err) => (this.error = err?.error?.message ?? 'Failed to reject expense'),
    });
  }

  voidIt(): void {
    if (!this.expense) return;
    const reason = prompt('Reason for voiding this expense (optional):') ?? '';
    if (!confirm('Void this expense? This reverses its posted entry — it cannot be undone.')) return;
    this.error = null;
    this.expenseApi.voidExpense(this.expense.id, reason || null).subscribe({
      next: () => this.load(),
      error: (err) => (this.error = err?.error?.message ?? 'Failed to void expense'),
    });
  }

  settle(): void {
    if (!this.expense) return;
    this.error = null;
    this.expenseApi.settle(this.expense.id, new Date().toISOString().slice(0, 10)).subscribe({
      next: () => this.load(),
      error: (err) => (this.error = err?.error?.message ?? 'Failed to record settlement'),
    });
  }

  statusClass(status: string): string {
    switch (status) {
      case 'PENDING':
        return 'badge-secondary';
      case 'APPROVED':
        return 'badge-success';
      case 'REJECTED':
      case 'VOIDED':
        return 'badge-danger';
      default:
        return 'badge-secondary';
    }
  }
}
